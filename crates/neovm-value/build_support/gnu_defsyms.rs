//! Generator for the GNU DEFSYM boot-membership table.
//!
//! GNU 31.1's `DEFSYM` is an empty placeholder macro (`src/lisp.h:2395`,
//! "Placeholder for make-docfile to process"; the real definition is done by
//! lread.c's `define_symbol`). The symbols it names live in the generated
//! `defsym_name[]` / `lispsym` arrays (`src/globals.h`, written by
//! `make-docfile -g`), and `init_obarray_once` (`src/lread.c:5193-5203`)
//! interns every one of them into the initial obarray before any Lisp runs.
//! A spelling that a build compiled in therefore exists in `(obarray)` with no
//! function, no value and an empty plist, which is why e.g.
//! `(intern-soft "buffer-or-string-p")` is a symbol in GNU and was missing
//! here.
//!
//! The checked-in ledger (`gnu_defsyms.snapshot.tsv`) records the extraction
//! from the pinned GNU source: one row per distinct DEFSYM spelling, with the
//! gate that decides whether a Neo build interns it and the source file the
//! decision came from. The generated table
//! (`crates/neovm-value/src/intern/gnu_defsyms.generated.rs`) is rendered from
//! the ledger alone, so the in-suite drift guard runs without a GNU checkout.
//!
//! ## Order
//!
//! `make-docfile.c:638-667` sorts the symbol globals by the C `Q...`
//! identifier: `Qnil Q t Qunbound Qerror Qlambda` first ("common symbols in
//! decreasing popularity order"), then `strcmp` of the identifier. GNU interns
//! in exactly that order, and the obarray completion order reverses insertion
//! within a hash bucket, so the table keeps it byte-for-byte.
//!
//! ## Gates
//!
//! `make-docfile -g` only sees the sources a configuration compiles
//! (`src/Makefile`'s `GLOBAL_SOURCES`). Splitting the spellings by the file
//! that defines them reproduces that set exactly, measured against the
//! attested oracle (profile `--with-x-toolkit=gtk3 --without-pgtk
//! --with-tree-sitter --with-dbus --with-native-compilation=no ...`): every
//! `common` spelling is interned there, and the non-`common` ones the oracle
//! does have come from runtime interning (font families, X atoms), not from
//! `defsym_name[]`.
//!
//! * `common`     - compiled on every supported build; always interned.
//! * `windows`    - only `w32*` sources; interned on `cfg!(windows)`.
//! * `macos`      - only `ns*`/`macfont.m` sources; on `cfg!(target_os = "macos")`.
//! * `unsupported`- only backends this port does not build (Haiku, Android,
//!                  PGTK, SFNT, Xwidgets, GFile notifications, kqueue, Xft,
//!                  MS-DOS); never interned.
//! * `uninterned` - GNU interns the spelling and then removes it again, or
//!                  deliberately keeps the symbol uninterned; never interned.
//!
//! Regenerate with `cargo xtask gnu-defsyms [--source <GNU checkout>]`; verify
//! with `--check` (add `--source` to also re-check the ledger against the
//! pinned source).

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};


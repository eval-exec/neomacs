pub const GENERATED: &str = "crates/neovm-value/src/intern/gnu_defsyms.generated.rs";
pub const PINNED_COMMIT: &str = "a360712c9d272d950d8d8255ef74570f7e90b7d9";

/// The source that defines the measured platform set.
pub const REFERENCE_CONFIGURE: &str = "--with-x-toolkit=gtk3 --without-pgtk --with-tree-sitter --with-dbus \
     --with-native-compilation=no --with-gnutls=ifavailable --with-xml2=ifavailable";

const LEDGER_HEADER: &str = "# name\tgate\tc-name\tsource\n\
     # Generated by `cargo xtask gnu-defsyms` from the pinned GNU 31.1 source\n\
     # (a360712c9d272d950d8d8255ef74570f7e90b7d9); see\n\
     # crates/neovm-value/build_support/gnu_defsyms.rs for the gate rules.\n\
     # Do not edit by hand.\n";

/// One distinct DEFSYM spelling and the decision to intern it at boot.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Row {
    /// The Lisp spelling (`DEFSYM`'s second argument).
    pub name: String,
    /// The gate that decides whether this build interns the spelling.
    pub gate: Gate,
    /// The C `Q...` identifier (make-docfile's sort key).
    pub c_name: String,
    /// The GNU source file the row's gate is derived from.
    pub source: String,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum Gate {
    Common,
    Windows,
    Macos,
    Unsupported,
    Uninterned,
}

impl Gate {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Common => "common",
            Self::Windows => "windows",
            Self::Macos => "macos",
            Self::Unsupported => "unsupported",
            Self::Uninterned => "uninterned",
        }
    }

    fn parse(text: &str) -> Option<Self> {
        match text {
            "common" => Some(Self::Common),
            "windows" => Some(Self::Windows),
            "macos" => Some(Self::Macos),
            "unsupported" => Some(Self::Unsupported),
            "uninterned" => Some(Self::Uninterned),
            _ => None,
        }
    }

    /// Whether the generated table carries this row (and the boot seeder
    /// interns it on the matching platform).
    pub const fn is_emitted(self) -> bool {
        matches!(self, Self::Common | Self::Windows | Self::Macos)
    }
}

/// Spellings GNU interns and then explicitly removes again at startup.
///
/// `get-file-char` / `get-emacs-mule-file-char` are `Funintern`ed in
/// `syms_of_lread` (`src/lread.c:5872-5873`), `outermost-restriction` in
/// `syms_of_editfns` (`src/editfns.c:4866`), `internal-interpreter-environment`
/// in `syms_of_eval` (`src/eval.c:4597`) and
/// `print--unreadable-callback-buffer` in `syms_of_print` (`src/print.c:3063`).
/// `unbound` is never interned: `define_symbol` skips `Qunbound` so a Lisp
/// program can own a symbol of that spelling (`src/lread.c:4762-4771`).
const UNINTERNED: &[&str] = &[
    "unbound",
    "get-file-char",
    "get-emacs-mule-file-char",
    "outermost-restriction",
    "internal-interpreter-environment",
    "print--unreadable-callback-buffer",
];

/// `make-docfile`'s popularity ranking (`lib-src/make-docfile.c:649-663`).
fn common_symbol_rank(c_name: &str) -> u8 {
    match c_name {
        "Qnil" => 0,
        "Qt" => 1,
        "Qunbound" => 2,
        "Qerror" => 3,
        "Qlambda" => 4,
        _ => u8::MAX,
    }
}

/// The make-docfile ordering key: commonsym rank, then `strcmp` of the C
/// identifier.
pub fn sort_key(row: &Row) -> (u8, &str) {
    (common_symbol_rank(&row.c_name), row.c_name.as_str())
}

/// Which gate a DEFSYM in `file` gets, from the source file alone.
fn gate_for_file(file: &str) -> Gate {
    if file.starts_with("w32") {
        return Gate::Windows;
    }
    if file.starts_with("ns") || file == "macfont.m" {
        return Gate::Macos;
    }
    const UNSUPPORTED_PREFIXES: &[&str] = &[
        "haiku",
        "android",
        "pgtk",
        "sfntfont",
        "xwidget",
        "gfilenotify",
        "kqueue",
        "xftfont",
        "msdos",
        "dosfns",
        "w16select",
    ];
    if UNSUPPORTED_PREFIXES
        .iter()
        .any(|prefix| file.starts_with(prefix))
        || file.contains("android")
    {
        return Gate::Unsupported;
    }
    Gate::Common
}

fn gate_rank(gate: Gate) -> u8 {
    match gate {
        Gate::Common => 0,
        Gate::Windows => 1,
        Gate::Macos => 2,
        Gate::Unsupported => 3,
        Gate::Uninterned => 4,
    }
}

/// Read every `DEFSYM (Qname, "spelling")` occurrence in one GNU source file.
fn scan_source(file_name: &str, text: &str, out: &mut Vec<Row>) {
    let gate = gate_for_file(file_name);
    let bytes = text.as_bytes();
    for (offset, _) in text.match_indices("DEFSYM") {
        // A real DEFSYM token: not the tail of a longer identifier.
        if offset > 0 && (bytes[offset - 1].is_ascii_alphanumeric() || bytes[offset - 1] == b'_') {
            continue;
        }
        let mut cursor = offset + "DEFSYM".len();
        let skip_ws = |cursor: &mut usize| {
            while *cursor < bytes.len() && bytes[*cursor].is_ascii_whitespace() {
                *cursor += 1;
            }
        };
        skip_ws(&mut cursor);
        if bytes.get(cursor) != Some(&b'(') {
            continue;
        }
        cursor += 1;
        skip_ws(&mut cursor);
        let ident_start = cursor;
        while cursor < bytes.len()
            && (bytes[cursor].is_ascii_alphanumeric() || bytes[cursor] == b'_')
        {
            cursor += 1;
        }
        let c_name = &text[ident_start..cursor];
        if !c_name.starts_with('Q') {
            continue;
        }
        skip_ws(&mut cursor);
        if bytes.get(cursor) != Some(&b',') {
            continue;
        }
        cursor += 1;
        skip_ws(&mut cursor);
        if bytes.get(cursor) != Some(&b'"') {
            continue;
        }
        cursor += 1;
        let mut name = String::new();
        let mut closed = false;
        while cursor < bytes.len() {
            match bytes[cursor] {
                b'\\' => {
                    let escaped = bytes.get(cursor + 1).copied();
                    match escaped {
                        Some(b'"') => name.push('"'),
                        Some(b'\\') => name.push('\\'),
                        Some(other) => {
                            // No DEFSYM spelling in the pinned source needs
                            // another escape; keep the byte so drift is loud
                            // in the ledger instead of silently normalised.
                            name.push(other as char);
                        }
                        None => break,
                    }
                    cursor += 2;
                }
                b'"' => {
                    cursor += 1;
                    closed = true;
                    break;
                }
                byte => {
                    name.push(byte as char);
                    cursor += 1;
                }
            }
        }
        if !closed || name.is_empty() {
            continue;
        }
        out.push(Row {
            name,
            gate,
            c_name: c_name.to_string(),
            source: file_name.to_string(),
        });
    }
}

/// Extract the ledger rows from the pinned GNU `src` directory.
pub fn extract(src_dir: &Path) -> Result<Vec<Row>, String> {
    let entries =
        fs::read_dir(src_dir).map_err(|error| format!("read {}: {error}", src_dir.display()))?;
    let mut files: Vec<PathBuf> = entries
        .filter_map(|entry| entry.ok().map(|entry| entry.path()))
        .filter(|path| {
            matches!(
                path.extension().and_then(|extension| extension.to_str()),
                Some("c") | Some("m")
            )
        })
        .collect();
    files.sort();
    if files.is_empty() {
        return Err(format!("no .c/.m sources under {}", src_dir.display()));
    }

    let mut occurrences = Vec::new();
    for path in &files {
        let file_name = path
            .file_name()
            .and_then(|name| name.to_str())
            .ok_or_else(|| format!("non-UTF-8 file name {}", path.display()))?;
        // Several GNU sources are Latin-1 (msdos.c among them); the DEFSYM
        // spellings themselves are ASCII, so a lossy decode cannot alter a
        // name and keeps the scan independent of the file's encoding.
        let bytes = fs::read(path).map_err(|error| format!("read {}: {error}", path.display()))?;
        let text = String::from_utf8_lossy(&bytes);
        scan_source(file_name, &text, &mut occurrences);
    }
    Ok(collapse(occurrences))
}

/// Collapse occurrences to one row per Lisp spelling, choosing the most
/// inclusive gate and, within it, the lexicographically first C identifier so
/// the result is deterministic. The only spelling with two C identifiers in
/// the pinned source is `static-color` (`Qstatic_color` in the common
/// `xfns.c`, `Qstatic_gray` in the Android-only `androidfns.c`); no build
/// compiles both, so either choice is faithful to that build.
///
/// Then collapse to one row per C identifier, because that is what
/// `make-docfile` does for its `defsym_name[]` array (it merges duplicate
/// names, `lib-src/make-docfile.c:693-706`). The pinned source has exactly one
/// such collision: `Qsans_serif` is `"sans-serif"` in the common `ftfont.c`
/// and `"sans_serif"` in the Windows-only `w32font.c`. Only Windows compiles
/// both, where make-docfile keeps the first sorted spelling; preferring the
/// more inclusive gate keeps the common `"sans-serif"` row, which is also what
/// a Windows build interns.
fn collapse(occurrences: Vec<Row>) -> Vec<Row> {
    let mut by_name: std::collections::BTreeMap<String, Row> = std::collections::BTreeMap::new();
    for row in occurrences {
        let gate = if UNINTERNED.contains(&row.name.as_str()) {
            Gate::Uninterned
        } else {
            row.gate
        };
        let candidate = Row { gate, ..row };
        match by_name.get(&candidate.name) {
            None => {
                by_name.insert(candidate.name.clone(), candidate);
            }
            Some(existing) => {
                let replace = (gate_rank(candidate.gate), &candidate.c_name)
                    < (gate_rank(existing.gate), &existing.c_name);
                if replace {
                    by_name.insert(candidate.name.clone(), candidate);
                }
            }
        }
    }
    // One row per C identifier, mirroring make-docfile's merged
    // `defsym_name[]` entries.
    let mut by_c_name: std::collections::BTreeMap<String, Row> = std::collections::BTreeMap::new();
    for row in by_name.into_values() {
        match by_c_name.get(&row.c_name) {
            None => {
                by_c_name.insert(row.c_name.clone(), row);
            }
            Some(existing) => {
                let replace =
                    (gate_rank(row.gate), &row.name) < (gate_rank(existing.gate), &existing.name);
                if replace {
                    by_c_name.insert(row.c_name.clone(), row);
                }
            }
        }
    }
    let mut rows: Vec<Row> = by_c_name.into_values().collect();
    rows.sort_by(|left, right| sort_key(left).cmp(&sort_key(right)));
    rows
}

/// Resolve `--source`: accepts the GNU checkout root or its `src` directory.
pub fn source_src_dir(source: &Path) -> Result<PathBuf, String> {
    if source.join("src").join("lisp.h").is_file() {
        return Ok(source.join("src"));
    }
    if source.join("lisp.h").is_file() {
        return Ok(source.to_path_buf());
    }
    Err(format!(
        "{} does not look like a GNU Emacs checkout (or its src directory)",
        source.display()
    ))
}

pub fn render_ledger(rows: &[Row]) -> String {
    let mut out = String::from(LEDGER_HEADER);
    for row in rows {
        writeln!(
            out,
            "{}\t{}\t{}\t{}",
            row.name,
            row.gate.as_str(),
            row.c_name,
            row.source
        )
        .expect("write to String");
    }
    out
}

pub fn parse_ledger(text: &str) -> Result<Vec<Row>, String> {
    let mut rows = Vec::new();
    for (index, line) in text.lines().enumerate() {
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let fields: Vec<&str> = line.split('\t').collect();
        if fields.len() != 4 {
            return Err(format!(
                "ledger line {}: expected 4 tab-separated fields, got {}",
                index + 1,
                fields.len()
            ));
        }
        let gate = Gate::parse(fields[1])
            .ok_or_else(|| format!("ledger line {}: unknown gate `{}`", index + 1, fields[1]))?;
        rows.push(Row {
            name: fields[0].to_string(),
            gate,
            c_name: fields[2].to_string(),
            source: fields[3].to_string(),
        });
    }
    if rows.is_empty() {
        return Err("ledger is empty".to_string());
    }
    Ok(rows)
}

const GENERATED_HEADER: &str = r#"// Generated by the GNU DEFSYM boot-membership generator (`cargo xtask gnu-defsyms`).
// Source of truth: crates/neovm-value/src/intern/gnu_defsyms.snapshot.tsv,
// extracted from GNU 31.1 a360712c9d272d950d8d8255ef74570f7e90b7d9.
// Do not edit by hand; run the generator and commit its output.
//
// GNU's `init_obarray_once` (src/lread.c:5193-5203) interns every compiled
// `defsym_name[]` spelling into the initial obarray with no function cell and
// no value; `make-docfile.c:638-667` fixes the order (Qnil, Qt, Qunbound,
// Qerror, Qlambda first, then strcmp of the C identifier). See
// crates/neovm-value/build_support/gnu_defsyms.rs for the gate rules.

/// Which builds intern a row, mirroring the `#ifdef` that compiles the
/// source file defining it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum DefsymGate {
    /// Every build compiles the defining source.
    Common,
    /// Only the Windows backend defines the spelling.
    Windows,
    /// Only the Cocoa/NextStep backend defines the spelling.
    Macos,
}

impl DefsymGate {
    /// Whether the spelling belongs to this build's obarray.
    pub(crate) const fn is_active(self) -> bool {
        match self {
            Self::Common => true,
            Self::Windows => cfg!(windows),
            Self::Macos => cfg!(target_os = "macos"),
        }
    }
}

"#;

pub fn render_generated(rows: &[Row]) -> Result<String, String> {
    let emitted: Vec<&Row> = rows.iter().filter(|row| row.gate.is_emitted()).collect();
    if emitted.is_empty() {
        return Err("no emitted rows in the ledger".to_string());
    }
    for pair in emitted.windows(2) {
        let left = sort_key(pair[0]);
        let right = sort_key(pair[1]);
        if left > right {
            return Err(format!(
                "ledger is not in make-docfile order: `{}` after `{}`",
                pair[1].c_name, pair[0].c_name
            ));
        }
    }
    let mut out = String::from(GENERATED_HEADER);
    writeln!(
        out,
        "/// Every GNU DEFSYM spelling this platform interns at boot, in\n\
         /// make-docfile order. {} rows.\n\
         #[rustfmt::skip]\n\
         pub(crate) static GNU_DEFSYMS: &[(&str, DefsymGate)] = &[",
        emitted.len()
    )
    .expect("write to String");
    for row in &emitted {
        let gate = match row.gate {
            Gate::Common => "Common",
            Gate::Windows => "Windows",
            Gate::Macos => "Macos",
            Gate::Unsupported | Gate::Uninterned => {
                return Err(format!("row `{}` has a non-emitted gate", row.name));
            }
        };
        writeln!(
            out,
            "    ({}, DefsymGate::{}),",
            rust_string_literal(&row.name),
            gate
        )
        .expect("write to String");
    }
    out.push_str("];\n");
    writeln!(
        out,
        "\nconst _: () = assert!(GNU_DEFSYMS.len() == {});",
        emitted.len()
    )
    .expect("write to String");
    Ok(out)
}

fn rust_string_literal(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for character in text.chars() {
        match character {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            other => out.push(other),
        }
    }
    out.push('"');
    out
}

/// Render the generated table from the checked-in ledger.
pub fn rendered(repo_root: &Path) -> Result<String, String> {
    let ledger_path = repo_root.join(LEDGER);
    let text = fs::read_to_string(&ledger_path)
        .map_err(|error| format!("read {}: {error}", ledger_path.display()))?;
    let rows = parse_ledger(&text)?;
    render_generated(&rows)
}

/// Write (or `--check`) the ledger and generated table.
pub fn generate(repo_root: &Path, check: bool, source: Option<&Path>) -> Result<(), String> {
    let ledger_path = repo_root.join(LEDGER);
    let generated_path = repo_root.join(GENERATED);

    if source.is_none() && !check {
        return Err(
            "writing needs the pinned GNU source: pass --source <checkout> or set GNU_EMACS_SOURCE"
                .to_string(),
        );
    }

    let extracted = match source {
        Some(source) => {
            let src_dir = source_src_dir(source)?;
            let rows = extract(&src_dir)?;
            Some((src_dir, rows))
        }
        None => None,
    };

    if let Some((src_dir, rows)) = &extracted {
        let extracted_ledger = render_ledger(rows);
        if check {
            let tracked = fs::read_to_string(&ledger_path)
                .map_err(|error| format!("read {}: {error}", ledger_path.display()))?;
            if tracked != extracted_ledger {
                return Err(format!(
                    "{LEDGER} is stale against {}; run `cargo xtask gnu-defsyms --source <checkout>`",
                    src_dir.display()
                ));
            }
        } else {
            fs::write(&ledger_path, &extracted_ledger)
                .map_err(|error| format!("write {}: {error}", ledger_path.display()))?;
        }
    }

    let rows = match extracted {
        Some((_, rows)) => rows,
        None => {
            let text = fs::read_to_string(&ledger_path)
                .map_err(|error| format!("read {}: {error}", ledger_path.display()))?;
            parse_ledger(&text)?
        }
    };

    let generated = render_generated(&rows)?;
    if check {
        let tracked = fs::read_to_string(&generated_path)
            .map_err(|error| format!("read {}: {error}", generated_path.display()))?;
        if tracked != generated {
            return Err(format!(
                "{GENERATED} is stale; run `cargo xtask gnu-defsyms`"
            ));
        }
    } else {
        fs::write(&generated_path, &generated)
            .map_err(|error| format!("write {}: {error}", generated_path.display()))?;
    }
    Ok(())
}

#[test]
fn combo_eieio_pb2_forward_scan() {
    return_if_neovm_enable_oracle_proptest_not_set!();

    let expect = expect_test::expect![[r#""ERR (void-function defmethod)""#]];
    crate::common::assert_oracle_parity_expect(
        r#"(progn
  (defclass bsc2 ()
    ((buf-name :initarg :buf :accessor b2-buf :initform "")
     (bounds :initarg :bounds :accessor b2-bounds :initform nil)
     (prop :initarg :prop :accessor b2-prop :initform 'face)
     (log :initarg :log :accessor b2-log :initform nil)))
  (defmethod b2-scan ((s bsc2) start limit)
    (with-current-buffer (b2-buf s)
      (let ((pos start)
            (prop (b2-prop s))
            (found nil)
            (count 0))
        (while (and pos (< pos limit) (< count 20))
          (let ((next (next-single-char-property-change pos prop nil limit)))
            (when (and next (< next limit))
              (push next found)
              (setq count (1+ count)))
            (setq pos (or next limit))))
        (push (format "scan:%d-%d:%d" start limit (length found)) (b2-log s))
        (setq found (reverse found))
        (setf (b2-bounds s) found)
        found)))
  (let* ((buf (generate-new-buffer "pb2_1"))
         (s (bsc2 :buf (buffer-name buf) :bounds nil :prop 'zone :log nil))
         (results nil))
    (with-current-buffer buf
      (insert "AAAA-BBBB-CCCC-DDDD-EEEE-FFFF-GGGG-HHHH")
      (put-text-property 1 5 'zone 'a)
      (put-text-property 6 10 'zone 'b)
      (put-text-property 11 15 'zone 'c)
      (put-text-property 16 20 'zone 'd)
      (put-text-property 21 25 'zone 'e)
      (put-text-property 26 30 'zone 'f)
      (put-text-property 31 35 'zone 'g)
      (put-text-property 36 40 'zone 'h)
      (setq-local my-b2-log nil)
      (let* ((ov (make-overlay 6 30))
             (_ (overlay-put ov 'zone 'overlay-zone))
             (_ (overlay-put ov 'priority 5))
             (m (set-marker (make-marker) 15)))
        (setq buffer-undo-list nil)
        (undo-boundary)
        (push (list "scan1" (b2-scan s 1 40) (marker-position m)) results)
        (goto-char 8)
        (insert "XXX")
        (setq my-b2-log (cons "ins@8" my-b2-log))
        (push (list "scan2" (b2-scan s 1 50) (marker-position m)) results)
        (save-restriction
          (narrow-to-region 5 40)
          (push (list "narrow" (b2-scan s 5 40) (point-min) (point-max)
                      (marker-position m)) results))
        (setq results (reverse results))
        (goto-char (point-max))
        (insert (format " | results=%S" results))
        (set-marker m 3)
        (list (buffer-substring-no-properties 1 (point-max))
              (b2-bounds s) (b2-log s)
              (marker-position m)
              (overlay-start ov) (overlay-end ov)
              my-b2-log)))
    (kill-buffer buf)))"#,
        expect,
    );
}


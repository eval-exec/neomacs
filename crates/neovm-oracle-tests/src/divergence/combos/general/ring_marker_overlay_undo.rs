//! Deep combo: ring × make-ring × ring-insert × ring-ref × ring-remove ×
//! ring-length × marker × overlay × textprop × undo × buffer-local × narrow.
//!
//! Stresses ring data structure with buffer state: creating rings, inserting
//! elements, referencing/removing elements while preserving markers, overlays,
//! text properties, and undo state. Rings are a common data structure in Emacs
//! (kill-ring, mark-ring, etc.) and must interact correctly with buffer state.

use crate::common::assert_oracle_parity;
use crate::common::return_if_neovm_enable_oracle_proptest_not_set;

#[test]
fn combo_ring_insert_ref_marker_overlay_undo() {
    return_if_neovm_enable_oracle_proptest_not_set!();

    let expect = expect_test::expect![[r#""ERR (wrong-type-argument listp t)""#]];
    crate::common::assert_oracle_parity_expect(
        r#"(progn
  (let ((buf (generate-new-buffer " combo-ring"))
        (ring (make-ring 5)))
    (with-current-buffer buf
      (insert "AAAA-BBBB-CCCC")
      (put-text-property 1 5 'zone 'a)
      (put-text-property 6 10 'zone 'b)
      (put-text-property 11 15 'zone 'c)
      (let ((m1 (copy-marker 5 nil))
            (m2 (copy-marker 10 t))
            (ov (make-overlay 1 15)))
        (overlay-put ov 'scope 'all)
        (undo-boundary)
        (ring-insert ring 'first)
        (ring-insert ring 'second)
        (ring-insert ring 'third)
        (goto-char 5)
        (insert (format "-<%s:%s:%s>-" (ring-ref ring 0) (ring-ref ring 1) (ring-ref ring 2)))
        (let ((after (list (buffer-string)
                           (ring-length ring)
                           (ring-ref ring 0)
                           (ring-ref ring 1)
                           (ring-ref ring 2)
                           (marker-position m1)
                           (marker-position m2)
                           (overlay-start ov) (overlay-end ov)
                           (get-text-property 1 'zone)
                           (get-text-property 6 'zone))))
          (primitive-undo 1 buffer-undo-list)
          (let ((restored (list (buffer-string)
                                (marker-position m1)
                                (marker-position m2)
                                (overlay-start ov) (overlay-end ov)
                                (get-text-property 1 'zone)
                                (get-text-property 6 'zone)
                                (get-text-property 11 'zone))))
            (kill-buffer buf)
            (list after restored))))))) "#,
        expect,
    );
}


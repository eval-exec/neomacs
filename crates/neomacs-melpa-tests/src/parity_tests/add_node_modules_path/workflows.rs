/// The package's headline workflow, from the README: a developer opens a file
/// in a node project whose `eslint' is installed locally and runs
/// `M-x add-node-modules-path'.  Before the command the project's linter cannot
/// be reached at all; after it `executable-find' and `call-process' both reach
/// exactly that project's copy, the editor's own `exec-path' is still intact
/// underneath, and the change is confined to this buffer -- a second buffer
/// visiting a file outside the project still cannot run `eslint', and switching
/// back finds the project path again.
///
/// The recorded tool log is what proves the shell command ran in the visited
/// file's directory rather than in the editor's working directory.
fn running_the_command_in_a_project_buffer_puts_that_projects_eslint_on_exec_path()
-> ParityBatchCase {
    ParityBatchCase::value(
        "running_the_command_in_a_project_buffer_puts_that_projects_eslint_on_exec_path",
        r##"(progn
  (anmp-install-tools)
  (let* ((project (anmp-project
                   "solo-app"
                   "{\n  \"name\": \"solo-app\",\n  \"version\": \"1.4.0\"\n}\n"
                   '("eslint" . "eslint 8.57.1 (solo-app)")))
         (source (anmp-write (expand-file-name "src/index.js" project)
                             "export const greet = (who) => `hi ${who}`;\n"))
         (outside (anmp-write (expand-file-name "scratch/notes.js" anmp-root)
                              "// not part of any node project\n"))
         (global-before (copy-sequence (default-value 'exec-path)))
         (observed nil))
    (setopt add-node-modules-path-command '("pnpm bin"))
    (global-set-key (kbd "C-c n") #'add-node-modules-path)
    (anmp-visit source)
    (push (list :on-arrival
                (list :mode major-mode
                      :path (anmp-exec-path-state)
                      :eslint (anmp-run "eslint")))
          observed)
    (execute-kbd-macro (kbd "C-c n"))
    (push (list :after-the-command
                (list :path (anmp-exec-path-state)
                      :eslint (anmp-run "eslint")))
          observed)
    (anmp-visit outside)
    (push (list :buffer-outside-the-project
                (list :path (anmp-exec-path-state)
                      :eslint (anmp-run "eslint")))
          observed)
    (anmp-visit source)
    (push (list :back-in-the-project
                (list :path (anmp-exec-path-state)
                      :eslint (anmp-run "eslint")))
          observed)
    (push (list :tools (anmp-tool-calls)
                :global-exec-path-unchanged
                (equal (default-value 'exec-path) global-before))
          observed)
    (nreverse observed)))"##,
        expect![[
            r#"OK ((:on-arrival (:mode js-mode :path (:buffer-local nil :added nil :global-tail-intact t) :eslint (:found nil))) (:after-the-command (:path (:buffer-local t :added ("solo-app/node_modules/.bin") :global-tail-intact t) :eslint (:found "solo-app/node_modules/.bin/eslint" :status 0 :output "eslint 8.57.1 (solo-app)"))) (:buffer-outside-the-project (:path (:buffer-local nil :added nil :global-tail-intact t) :eslint (:found nil))) (:back-in-the-project (:path (:buffer-local t :added ("solo-app/node_modules/.bin") :global-tail-intact t) :eslint (:found "solo-app/node_modules/.bin/eslint" :status 0 :output "eslint 8.57.1 (solo-app)"))) (:tools ("pnpm bin @ solo-app/src") :global-exec-path-unchanged t))"#
        ]],
    )
}


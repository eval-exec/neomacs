fn invoking_the_freshly_installed_autoload_loads_the_library_and_completes_the_workflow()
-> ParityBatchCase {
    ParityBatchCase::value(
        "invoking_the_freshly_installed_autoload_loads_the_library_and_completes_the_workflow",
        r##"(progn
  (anmp-install-tools)
  (let* ((project (anmp-project
                   "installed-app"
                   "{\n  \"name\": \"installed-app\",\n  \"version\": \"5.2.0\"\n}\n"
                   '("eslint" . "eslint 9.9.0 (installed-app)")))
         (source (anmp-write (expand-file-name "src/index.js" project) "// index\n"))
         (before nil))
    (setq-default add-node-modules-path-command '("pnpm bin"))
    (global-set-key (kbd "C-c n") #'add-node-modules-path)
    (anmp-visit source)
    (setq before
          (list :library-loaded (featurep 'add-node-modules-path)
                :still-an-autoload
                (and (fboundp 'add-node-modules-path)
                     (autoloadp (symbol-function 'add-node-modules-path))
                     t)
                :commandp (and (commandp 'add-node-modules-path) t)
                :path (anmp-exec-path-state)
                :eslint (anmp-run "eslint")))
    (execute-kbd-macro (kbd "C-c n"))
    (list :freshly-installed before
          :after-one-keystroke
          (list :library-loaded (featurep 'add-node-modules-path)
                :still-an-autoload
                (and (autoloadp (symbol-function 'add-node-modules-path)) t)
                :path (anmp-exec-path-state)
                :eslint (anmp-run "eslint"))
          :tools (anmp-tool-calls))))"##,
        expect![[
            r#"OK (:freshly-installed (:library-loaded nil :still-an-autoload t :commandp t :path (:buffer-local nil :added nil :global-tail-intact t) :eslint (:found nil)) :after-one-keystroke (:library-loaded t :still-an-autoload nil :path (:buffer-local t :added ("installed-app/node_modules/.bin") :global-tail-intact t) :eslint (:found "installed-app/node_modules/.bin/eslint" :status 0 :output "eslint 9.9.0 (installed-app)")) :tools ("pnpm bin @ installed-app/src"))"#
        ]],
    )
}


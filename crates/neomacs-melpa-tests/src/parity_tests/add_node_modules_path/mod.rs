const ADD_NODE_MODULES_PATH_TEST_TIMEOUT: Duration = Duration::from_secs(180);

/// Sandbox helpers shared by the workflows.
///
/// add-node-modules-path runs shell commands in the visited file's directory,
/// treats each command's output as a directory name, and prepends the ones that
/// exist to a buffer local `exec-path' so the project's own `eslint' wins over
/// anything installed globally.  Its whole value is therefore filesystem
/// shaped, so the workflows build real node projects below the per-case sandbox
/// with real executables in `node_modules/.bin', and assert what the user can
/// now run rather than what the package returned.
///
/// The external boundary is `pnpm' and `npm'.  Both are installed as recording
/// stand-ins first on `PATH'; each logs its exact argv and working directory,
/// and each replays behaviour recorded from the real tool rather than an
/// invented reply:
///
/// * pnpm 11.1.2 `bin' prints `<nearest package.json directory>/node_modules/.bin'
///   and exits 0 -- including from a nested subdirectory, and including when no
///   `package.json' exists anywhere above, where it falls back to the working
///   directory and so names a directory that is not there.
/// * pnpm 11.1.2 `bin -w' prints the workspace root's `node_modules/.bin', or
///   writes `[ERROR] --workspace-root may only be used inside a workspace' to
///   stderr and exits 1 outside a workspace.
/// * npm 10.9.7 has no `bin' subcommand -- it was removed in npm 9 -- and
///   prints its `Unknown command' help text on *stdout*, exiting 1.  That text
///   is reproduced byte for byte because the package puts it in front of the
///   user in a warning.
///
/// The pnpm stand-in was diffed against the real binary over seven directories
/// (workspace root, package, two nested subdirectories, and three directories
/// outside any workspace) times both argument vectors: stdout, stderr and exit
/// status agreed in all fourteen.
const ADD_NODE_MODULES_PATH_TEST_PRELUDE: &str = r##"
(require 'cl-lib)
(require 'seq)
(require 'subr-x)

(defvar anmp-root
  (file-name-as-directory (getenv "NEOMACS_TEST_SANDBOX_ROOT")))

(defvar anmp-tools
  (file-name-as-directory (expand-file-name "tools" anmp-root)))

(defvar anmp-tool-log (expand-file-name "tools.log" anmp-root))

(defun anmp-relative (path)
  "Spell PATH relative to the sandbox so snapshots stay stable."
  (if (stringp path) (file-relative-name path anmp-root) path))

(defun anmp-write (path content &optional executable)
  "Write CONTENT to PATH, creating its directory, and return PATH."
  (make-directory (file-name-directory path) t)
  (let ((coding-system-for-write 'utf-8-unix))
    (with-temp-buffer
      (insert content)
      (write-region (point-min) (point-max) path nil 'silent)))
  (when executable (set-file-modes path #o755))
  path)

(defconst anmp-pnpm-stand-in
  (string-join
   (list
    "#!/bin/sh"
    "# Stand-in for pnpm 11.1.2, replaying its recorded `bin' behaviour."
    "{ printf 'pnpm'"
    "  for anmp_argument in \"$@\"; do printf ' %s' \"$anmp_argument\"; done"
    "  printf ' @ %s\\n' \"$PWD\"; } >> \"$ANMP_TOOL_LOG\""
    "anmp_find_up() {"
    "  anmp_directory=$PWD"
    "  while :; do"
    "    if [ -e \"$anmp_directory/$1\" ]; then"
    "      printf '%s\\n' \"$anmp_directory\""
    "      return 0"
    "    fi"
    "    [ \"$anmp_directory\" = / ] && return 1"
    "    anmp_directory=$(dirname \"$anmp_directory\")"
    "  done"
    "}"
    "if [ \"$1\" = bin ] && [ \"$2\" = -w ]; then"
    "  if anmp_workspace=$(anmp_find_up pnpm-workspace.yaml); then"
    "    printf '%s/node_modules/.bin\\n' \"$anmp_workspace\""
    "    exit 0"
    "  fi"
    "  printf '[ERROR] --workspace-root may only be used inside a workspace\\n' >&2"
    "  exit 1"
    "fi"
    "if [ \"$1\" = bin ] && [ -z \"$2\" ]; then"
    "  anmp_project=$(anmp_find_up package.json) || anmp_project=$PWD"
    "  printf '%s/node_modules/.bin\\n' \"$anmp_project\""
    "  exit 0"
    "fi"
    "printf 'stand-in pnpm was given unrecorded arguments: %s\\n' \"$*\" >&2"
    "exit 2"
    "")
   "\n"))

(defconst anmp-npm-stand-in
  (string-join
   (list
    "#!/bin/sh"
    "# Stand-in for npm 10.9.7, which dropped `npm bin' in npm 9."
    "{ printf 'npm'"
    "  for anmp_argument in \"$@\"; do printf ' %s' \"$anmp_argument\"; done"
    "  printf ' @ %s\\n' \"$PWD\"; } >> \"$ANMP_TOOL_LOG\""
    "if [ \"$1\" = bin ] && [ -z \"$2\" ]; then"
    "  printf 'Unknown command: \"bin\"\\n\\nTo see a list of supported npm commands, run:\\n  npm help\\n'"
    "  exit 1"
    "fi"
    "printf 'stand-in npm was given unrecorded arguments: %s\\n' \"$*\" >&2"
    "exit 2"
    "")
   "\n"))

(defun anmp-install-tools ()
  "Install the recording `pnpm' and `npm' stand-ins first on `PATH'."
  (anmp-write (expand-file-name "pnpm" anmp-tools) anmp-pnpm-stand-in t)
  (anmp-write (expand-file-name "npm" anmp-tools) anmp-npm-stand-in t)
  (setenv "ANMP_TOOL_LOG" anmp-tool-log)
  (setenv "PATH" (concat (directory-file-name anmp-tools)
                         path-separator (getenv "PATH")))
  anmp-tools)

(defun anmp-tool-calls ()
  "Every stand-in invocation as `TOOL ARGUMENTS @ DIRECTORY'.

The directory is the point of this log: it is what proves the package ran the
command in the visited file's directory rather than in the editor's."
  (if (not (file-exists-p anmp-tool-log))
      'no-tool-was-run
    (with-temp-buffer
      (insert-file-contents anmp-tool-log)
      (mapcar
       (lambda (line)
         (if (string-match "\\`\\(.*\\) @ \\(.*\\)\\'" line)
             (concat (match-string 1 line) " @ "
                     (anmp-relative (match-string 2 line)))
           (copy-sequence line)))
       (split-string (buffer-string) "\n" t)))))

(defun anmp-install-binary (directory name label)
  "Install a real executable NAME below DIRECTORY that identifies itself."
  (anmp-write
   (expand-file-name name (expand-file-name "node_modules/.bin" directory))
   (string-join (list "#!/bin/sh"
                      (concat "printf '%s\\n' \"" label "\"")
                      "")
                "\n")
   t))

(defun anmp-project (relative package-json &rest binaries)
  "Create a node project at RELATIVE below the sandbox and return its directory.

BINARIES is a list of (NAME . LABEL) cells installed into `node_modules/.bin',
each printing LABEL so the workflow can tell which project's copy of a tool the
user actually reached."
  (let ((directory (file-name-as-directory
                    (expand-file-name relative anmp-root))))
    (make-directory directory t)
    (anmp-write (expand-file-name "package.json" directory) package-json)
    (dolist (binary binaries)
      (anmp-install-binary directory (car binary) (cdr binary)))
    directory))

(defun anmp-visit (path)
  "Open PATH the way a user does, without the repository's directory locals.

The sandbox lives inside the neomacs worktree, whose top level `.dir-locals.el'
would otherwise be applied to every file this suite visits, after the major mode
has run, and quietly reconfigure the buffer."
  (let* ((enable-dir-local-variables nil)
         (buffer (find-file-noselect path)))
    (set-window-buffer (selected-window) buffer)
    (set-buffer buffer)
    buffer))

(defun anmp-exec-path-state ()
  "What this buffer's `exec-path' now says, relative to the sandbox.

`:added' is what the package prepended, in order; `:global-tail-intact' says
the editor's own `exec-path' is still underneath it unchanged."
  (let* ((global (default-value 'exec-path))
         (added (butlast exec-path (length global))))
    (list :buffer-local (and (local-variable-p 'exec-path) t)
          :added (mapcar #'anmp-relative added)
          :global-tail-intact (equal (nthcdr (length added) exec-path) global))))

(defun anmp-run (program)
  "Run PROGRAM from this buffer the way the user now can.

`executable-find' and `call-process' both search `exec-path', so this reports
which project's copy of PROGRAM the buffer local path actually reaches."
  (let ((found (executable-find program)))
    (if (not found)
        (list :found nil)
      (let* ((output (generate-new-buffer " *anmp-output*"))
             (status (condition-case error
                         (call-process program nil output nil "--version")
                       (error (cons 'signal error))))
             (text (with-current-buffer output
                     (string-trim
                      (buffer-substring-no-properties
                       (point-min) (point-max))))))
        (kill-buffer output)
        (list :found (anmp-relative found) :status status :output text)))))

(defun anmp-echo-mark ()
  "Mark both logs, so a workflow reports only what the package itself said.

Scoping matters here rather than being tidiness: the harness `load's the
package source, which emits a `lexical-binding' warning of its own before any
workflow runs.  A capture of the whole *Warnings* buffer records that instead
of the package's warnings, and the case that claims the package says nothing at
all then asserts somebody else's sentence."
  (cons (with-current-buffer (get-buffer-create "*Messages*") (point-max))
        (with-current-buffer (get-buffer-create "*Warnings*") (point-max))))

(defun anmp-said-since (mark)
  "Return what the package put in front of the user since MARK."
  (list :messages
        (with-current-buffer (get-buffer-create "*Messages*")
          (split-string
           (buffer-substring-no-properties
            (min (car mark) (point-max)) (point-max))
           "\n" t))
        :warnings
        (with-current-buffer (get-buffer-create "*Warnings*")
          (buffer-substring-no-properties
           (min (cdr mark) (point-max)) (point-max)))))
"##;

fn add_node_modules_path_oracle(source_file: &str) -> CachedMelpaOracle {
    CachedMelpaOracle::new(ADD_NODE_MODULES_PATH_MELPA_PIN, source_file)
        .expect("prepare pinned add-node-modules-path source below ./tmp")
        .with_prelude(ADD_NODE_MODULES_PATH_TEST_PRELUDE)
        .with_timeout(ADD_NODE_MODULES_PATH_TEST_TIMEOUT)
}

fn current_test_name() -> String {
    let thread = std::thread::current();
    thread
        .name()
        .unwrap_or("unnamed add-node-modules-path parity test")
        .into()
}


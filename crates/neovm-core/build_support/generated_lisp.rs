//! **The single source of truth for the Lisp files this build generates.**
//!
//! GNU does not ship `lisp/international/charscript.el` or
//! `lisp/international/emoji-zwj.el`.  It *builds* them, and
//! `admin/unidata/Makefile.in:110-123` is the whole recipe:
//!
//! ```make
//! # Don't use $^, since that includes the awk script.
//! ${unidir}/charscript.el: ${blocks_sources}
//! 	$(AM_V_GEN)$(AWK) -f ${blocks} ${blocks_sources} > $@
//!
//! ${unidir}/emoji-zwj.el: ${zwj_sources}
//! 	$(AM_V_GEN)$(AWK) -f ${zwj} ${zwj_sources} > $@
//! ```
//!
//! One rule per file, no post-processing: **what awk prints is the file.**
//!
//! # Why this file exists
//!
//! Until ledger 206 this port had two producers for those two names:
//!
//! * `cargo xtask fresh-build` ran GNU's awk, as above.
//! * `neovm-core/build.rs` ran `build_support/unicode_gen.rs`, a hand-written
//!   Rust reimplementation of both awk scripts, over a second byte-identical
//!   copy of GNU's Unicode data in `crates/neovm-core/unicode-data/`.
//!
//! Whichever ran last decided the bytes, and they disagreed.  Two costs:
//!
//! 1. `write_if_changed` rewrote `emoji-zwj.el` on every profile switch, which
//!    left `emoji-zwj.elc` older than its source -- so the first debug build
//!    after a release build made the tree stale, by construction, every time.
//!    Ledger 203 §7.4.
//! 2. The reimplementation double-escaped the `\U0001F1E6`-style character
//!    escapes in the two hand-derived flag blocks, so the shipped image's
//!    `composition-function-table` held a 23-character literal where GNU holds
//!    the five-character regexp `[🇦-🇿]`.  Country flags and UK subdivision
//!    flags did not compose.  Ledger 206.
//!
//! Porting the awk more carefully was never the answer.  The project's
//! standing directive is not to reimplement what GNU already ships, and here
//! it cannot even be done: GNU's `for (elt in ch)` walks an awk associative
//! array, so its 150 emoji entries come out in gawk's internal hash order,
//! which no other language reproduces.
//!
//! # How to keep it one producer
//!
//! Every consumer includes THIS FILE and iterates
//! [`AWK_GENERATED_UNICODE_LISP`]; nobody writes those paths any other way:
//!
//! * `neovm-core/build.rs` -- `#[path = "build_support/generated_lisp.rs"]`
//! * `crates/xtask/src/main.rs` -- `#[path = "../../neovm-core/build_support/generated_lisp.rs"]`
//! * `crates/neovm-core/src/emacs_core/tests/build_support/generated_lisp.rs`, which runs the recipe
//!   and diffs the bytes on disk, so a third producer fails there by name
//!   whatever crate it lives in.
//!
//! This is the same arrangement as `jit/shim_names.rs`, which
//! `neovm-core/build.rs` and `crates/neomacs/build.rs` both `include!` so their
//! export sets cannot drift.
//!
//! Ledger 206.

#![allow(dead_code)]

use std::path::{Path, PathBuf};
use std::process::Command;

/// GNU's `$(AWK)`.  `configure` refuses a tree without one, and so does this.
pub const AWK_PROGRAM: &str = "awk";

/// GNU's directory of Unicode inputs and the awk scripts that read them.
///
/// There is one copy.  `crates/neovm-core/unicode-data/` was a second, and it existed
/// only to feed the reimplementation this file replaced.
pub const GNU_UNIDATA_DIR: &str = "admin/unidata";

/// Where GNU's Makefile puts the results (`${unidir}`).
pub const GENERATED_LISP_DIR: &str = "lisp";

/// One Lisp file this build generates by running one of GNU's own awk scripts.
///
/// Every field is a path GNU already has.  There is deliberately no field for
/// "produced some other way": a row cannot describe a Rust reimplementation,
/// because the only thing a row can name is a script and its inputs.
pub struct AwkGeneratedLisp {
    /// The generated file, relative to [`GENERATED_LISP_DIR`].
    pub output: &'static str,
    /// GNU's awk script, relative to [`GNU_UNIDATA_DIR`].
    pub script: &'static str,
    /// GNU's data files, relative to [`GNU_UNIDATA_DIR`], in GNU's own order.
    /// The order is observable: awk reads them as one concatenated stream.
    pub inputs: &'static [&'static str],
    /// The line in GNU's Makefile this row transcribes, so a reader can check
    /// it rather than trust it.
    pub gnu_rule: &'static str,
}

/// Every awk-generated Lisp file, in GNU's Makefile order.
///
/// `admin/unidata/Makefile.in` has exactly these two awk rules; the rest of
/// that Makefile's targets are generated by `unidata-gen.el` running inside a
/// bootstrap Emacs, which `xtask` drives separately because it needs a built
/// binary and a build script cannot have one.
pub const AWK_GENERATED_UNICODE_LISP: &[AwkGeneratedLisp] = &[
    AwkGeneratedLisp {
        output: "international/charscript.el",
        script: "blocks.awk",
        inputs: &["Blocks.txt", "emoji-data.txt"],
        gnu_rule: "admin/unidata/Makefile.in:111-112",
    },
    AwkGeneratedLisp {
        output: "international/emoji-zwj.el",
        script: "emoji-zwj.awk",
        inputs: &["emoji-zwj-sequences.txt", "emoji-sequences.txt"],
        gnu_rule: "admin/unidata/Makefile.in:122-123",
    },
];

/// The two trees a recipe touches, named rather than implied.
///
/// They are not always the same repository: `cargo xtask fresh-build` reads
/// GNU's scripts and data from the checkout (`repo_root/admin/unidata`) but
/// writes into whatever runtime tree it was pointed at
/// (`runtime_root/lisp`), which is how it builds an installed image.  A
/// recipe that took one root would silently write into the wrong one.
#[derive(Clone, Debug)]
pub struct GeneratedLispRoots {
    /// GNU's `admin/unidata`: the awk scripts and the Unicode data.
    pub unidata_dir: PathBuf,
    /// The `lisp/` tree the outputs belong in.
    pub lisp_root: PathBuf,
}

impl GeneratedLispRoots {
    /// The ordinary case: both trees are this checkout.
    pub fn of_project(project_root: &Path) -> Self {
        Self {
            unidata_dir: project_root.join(GNU_UNIDATA_DIR),
            lisp_root: project_root.join(GENERATED_LISP_DIR),
        }
    }

    /// A build that reads GNU's data from one tree and writes into another.
    pub fn new(unidata_dir: impl Into<PathBuf>, lisp_root: impl Into<PathBuf>) -> Self {
        Self {
            unidata_dir: unidata_dir.into(),
            lisp_root: lisp_root.into(),
        }
    }
}

/// What [`AwkGeneratedLisp::regenerate`] did.
///
/// `Unchanged` is the common case and the load-bearing one: leaving the mtime
/// alone is what stops a rebuild from invalidating the `.elc` beside it.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Regenerated {
    /// The bytes on disk already matched; nothing was written and no mtime
    /// moved.
    Unchanged,
    /// The file did not exist or held different bytes, and was rewritten.
    Written,
}

impl AwkGeneratedLisp {
    /// The generated file's absolute path.
    pub fn output_path(&self, roots: &GeneratedLispRoots) -> PathBuf {
        roots.lisp_root.join(self.output)
    }

    /// GNU's awk script's absolute path.
    pub fn script_path(&self, roots: &GeneratedLispRoots) -> PathBuf {
        roots.unidata_dir.join(self.script)
    }

    /// GNU's data files, in GNU's order.
    pub fn input_paths(&self, roots: &GeneratedLispRoots) -> Vec<PathBuf> {
        self.inputs
            .iter()
            .map(|name| roots.unidata_dir.join(name))
            .collect()
    }

    /// Every file the recipe reads: the script first, then its inputs.
    ///
    /// This is what a build system watches, and GNU watches the same set --
    /// `${unidir}/emoji-zwj.el` is declared to depend on `${zwj}` and on
    /// `${zwj_sources}` in two separate rules for exactly that reason.
    pub fn dependencies(&self, roots: &GeneratedLispRoots) -> Vec<PathBuf> {
        let mut deps = vec![self.script_path(roots)];
        deps.extend(self.input_paths(roots));
        deps
    }

    /// The command line this recipe runs, for a build log or a `--dry-run`.
    pub fn command_line(&self, roots: &GeneratedLispRoots) -> String {
        let mut line = format!("{AWK_PROGRAM} -f {}", self.script_path(roots).display());
        for input in self.input_paths(roots) {
            line.push(' ');
            line.push_str(&input.display().to_string());
        }
        format!("{line} > {}", self.output_path(roots).display())
    }

    /// Run GNU's awk and return exactly the bytes it printed.
    ///
    /// Nothing is written, and nothing is normalised: the caller compares or
    /// stores the bytes as they came out, because GNU's Makefile redirects
    /// awk's stdout straight into the file.
    pub fn generate(&self, roots: &GeneratedLispRoots) -> Result<Vec<u8>, String> {
        let script = self.script_path(roots);
        let inputs = self.input_paths(roots);
        for path in std::iter::once(&script).chain(inputs.iter()) {
            if !path.is_file() {
                return Err(format!(
                    "missing generator input {} (GNU {})",
                    path.display(),
                    self.gnu_rule
                ));
            }
        }

        let output = Command::new(AWK_PROGRAM)
            .arg("-f")
            .arg(&script)
            .args(&inputs)
            .output()
            .map_err(|err| {
                format!(
                    "could not run `{AWK_PROGRAM}` for {}: {err}.  GNU's build \
                     requires awk too ({}); install one (gawk) and rebuild",
                    self.output, self.gnu_rule,
                )
            })?;
        if !output.status.success() {
            return Err(format!(
                "`{AWK_PROGRAM} -f {}` exited {}: {}",
                script.display(),
                output.status,
                String::from_utf8_lossy(&output.stderr).trim(),
            ));
        }
        if output.stdout.is_empty() {
            return Err(format!(
                "`{AWK_PROGRAM} -f {}` printed nothing; {} would be empty",
                script.display(),
                self.output,
            ));
        }
        Ok(output.stdout)
    }

    /// Generate, and write only if the bytes differ.
    ///
    /// The "only if" is the whole point.  A build script that rewrote an
    /// identical file would move its mtime past the `.elc` compiled from it,
    /// and ledger 202's refusal would -- correctly -- stop every in-process
    /// test in the tree.
    pub fn regenerate(&self, roots: &GeneratedLispRoots) -> Result<Regenerated, String> {
        let generated = self.generate(roots)?;
        let output = self.output_path(roots);
        if std::fs::read(&output).is_ok_and(|current| current == generated) {
            return Ok(Regenerated::Unchanged);
        }
        if let Some(parent) = output.parent() {
            std::fs::create_dir_all(parent)
                .map_err(|err| format!("create {}: {err}", parent.display()))?;
        }
        std::fs::write(&output, &generated)
            .map_err(|err| format!("write {}: {err}", output.display()))?;
        Ok(Regenerated::Written)
    }
}

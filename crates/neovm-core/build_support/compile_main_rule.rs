//! **GNU's rule for which `.el` must have a `.elc`, in one place.**
//!
//! `lisp/Makefile.in`'s `compile-main` target (GNU Emacs 31.0.90,
//! `lisp/Makefile.in:363-382`) is a **scan, not a list**.  It globs every
//! `.el` under `${SUBDIRS_REL}` and consults exactly one thing about each
//! file -- the file's own text:
//!
//! ```sh
//! for el in $$els; do
//!   test -f $$el || continue;
//!   test ! -f $${el}c &&
//!       GREP_OPTIONS= grep '^;.*[^a-zA-Z]no-byte-compile: *t' $$el > /dev/null && \
//!       continue;
//!   echo "$${el}c";
//! done
//! ```
//!
//! Read it as the postcondition it implies and it says: **a `.el` may ship
//! without a `.elc` only if that file declares `no-byte-compile: t`.**  Where
//! the file came from -- hand-written, `awk`-generated, `loaddefs-generate`d,
//! `sed`-post-processed -- is not consulted anywhere.  Generated files are
//! swept up by the same glob as everything else; `compile-main`'s only
//! ordering concession to them is `| autoloads`, an order-only prerequisite.
//!
//! # Which generated files GNU compiles, and what decides it
//!
//! The question ledger 207 was handed was "should the build byte-compile
//! `cl-loaddefs.el`", and the answer is not a decision this port gets to make.
//! GNU already made it, in the generator, and wrote it into the bytes:
//!
//! * `loaddefs-generate--rubric` (`lisp/emacs-lisp/loaddefs-gen.el:501-528`)
//!   takes a COMPILE argument documented as *"If COMPILE, don't include a
//!   \"don't compile\" cookie"*, and hands it to `generate-lisp-file-trailer`
//!   as `:compile`.
//! * The Emacs build reaches `--rubric` through `loaddefs-generate` with
//!   INCLUDE-PACKAGE-VERSION `t` (`loaddefs-generate--emacs-batch`,
//!   `loaddefs-gen.el:742-766`), so `lisp/loaddefs.el`,
//!   `lisp/emacs-lisp/cl-loaddefs.el` and the other nineteen carry **no**
//!   cookie -- and GNU's own tree has a `.elc` for every one of them.
//! * The **second** `loaddefs-generate` call in that same function, the one
//!   that scans `../etc/themes/` into `lisp/theme-loaddefs.el`, passes no
//!   INCLUDE-PACKAGE-VERSION.  So that file DOES carry `no-byte-compile: t`,
//!   and GNU ships no `theme-loaddefs.elc`.  Neither should this port.
//! * `lisp/ldefs-boot.el` gets the cookie injected by `sed` in the Makefile
//!   rule itself (`lisp/Makefile.in:213-217`), so it is exempt too.
//!
//! So "must be byte-compiled" is **not a property of a recipe row**.  It is a
//! property of the generated bytes, written by the generator and read back by
//! a grep.  A `must_byte_compile: bool` field on an `AwkGeneratedLisp` recipe
//! row (`build_support/generated_lisp.rs`) would have been a *second producer
//! of the same fact*, which is precisely the defect ledger 206 closed one
//! level up.  This module therefore reads the file, exactly as GNU's Makefile
//! does, and offers no way to override it.
//!
//! # Why the verdict is an enum
//!
//! Ledger 202 gave this build a refusal for bytecode **older** than its
//! source.  That predicate is keyed on the `.elc`: it walks the `.elc` files
//! and asks each one for its `.el`.  A `.el` with **no** `.elc` has no key, so
//! it was invisible -- ledger 173's law again, and this time the missing row
//! is the whole defect.  [`BytecodeCoverage`] makes the third state nameable,
//! so a caller that handles "compiled" and "stale" can no longer forget
//! "absent".
//!
//! # How to keep it one rule
//!
//! Every consumer includes THIS FILE; nobody re-spells GNU's grep:
//!
//! * `crates/xtask/src/main.rs` -- decides what `compile-main` compiles, and what its
//!   `.elc`-deleting steps are allowed to delete.
//! * `crates/neovm-core/src/emacs_core/tests/build_support/compile_main_rule.rs` -- scans the tree
//!   this build actually ships and fails by name on any file GNU would have
//!   compiled and this build did not.
//!
//! Same arrangement as `generated_lisp.rs` (ledger 206) and
//! `jit/shim_names.rs`.
//!
//! Ledger 207.

#![allow(dead_code)]

use std::io;
use std::path::{Path, PathBuf};

/// GNU's `compile-main` verdict for one `.el`, as a state of the tree.
///
/// Deliberately three states and not a `bool`.  Two of them are healthy for
/// opposite reasons, and the third is the defect; collapsing any pair loses
/// the distinction that ledger 207 is about.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum BytecodeCoverage {
    /// A `.elc` exists beside the source.  GNU compiles it and so does this
    /// build; whether it is *current* is ledger 202's separate question.
    Compiled { compiled: PathBuf },
    /// No `.elc`, and the source itself declares `no-byte-compile: t`.  GNU's
    /// `compile-main` skips exactly these, so a missing `.elc` here is
    /// correct and must not be manufactured.
    ExemptBySourceCookie,
    /// No `.elc` and no cookie: GNU would have compiled this file and this
    /// tree has not.
    ///
    /// The cost is not only speed.  `Fload` hands a `.el` to
    /// `load-source-file-function` = `load-with-code-conversion`
    /// (`src/lread.c:1400-1418`, `lisp/international/mule.el:294-336`), which
    /// calls `insert-file-contents` -- and `Finsert_file_contents` assigns
    /// `Vlast_coding_system_used` (`src/fileio.c:5172`).  A `.elc` never
    /// reaches that path; `Fload` reads it from a raw stdio stream.  So a
    /// generated file that ships without its `.elc` silently rewrites the
    /// caller's coding state, from inside whatever `load` pulled it in.
    MissingBytecode,
}

impl BytecodeCoverage {
    /// Ask GNU's question of one `.el`.
    ///
    /// Errors only if the source cannot be read at all; an unreadable file is
    /// not a verdict.
    pub fn of(source: &Path) -> io::Result<Self> {
        let compiled = source.with_extension("elc");
        if compiled.is_file() {
            return Ok(Self::Compiled { compiled });
        }
        if source_declares_no_byte_compile(source)? {
            Ok(Self::ExemptBySourceCookie)
        } else {
            Ok(Self::MissingBytecode)
        }
    }

    /// Whether GNU's `compile-main` would echo `$(el)c` into `TARGETS`.
    ///
    /// True for [`Self::Compiled`] as well as [`Self::MissingBytecode`],
    /// because GNU's `test ! -f $${el}c &&` short-circuits: a file that
    /// already has a `.elc` is compiled again regardless of what its own text
    /// says.  That asymmetry is GNU's and is deliberate -- it is how a file
    /// that gained the cookie later still gets its stale `.elc` refreshed.
    pub fn compile_main_considers(&self) -> bool {
        !matches!(self, Self::ExemptBySourceCookie)
    }
}

/// GNU's `grep '^;.*[^a-zA-Z]no-byte-compile: *t'`, line by line.
///
/// Read the regexp as the four constraints it is, because each one is load
/// bearing and each one has a file it exists for:
///
/// * `^;` -- the line is a comment.  This is what stops `(setq
///   no-byte-compile t)` in ordinary code from exempting a file.
/// * `.*[^a-zA-Z]` -- at least one character stands between the `;` and the
///   marker, and the one immediately before it is not a letter.  This is what
///   stops `local-no-byte-compile:` (and `autoload-no-byte-compile:`) from
///   matching.  It also means the marker cannot start at index 1: `.*` begins
///   after the anchored `;`, so `[^a-zA-Z]` consumes index 1 at the earliest
///   and the marker begins at index 2.
/// * `: *t` -- spaces only, and `nil` does not match.
///
/// Kept exact rather than "close enough".  Every real Emacs file writes
/// `;; no-byte-compile: t` and would satisfy a looser test too, which is
/// precisely why a looser test would never be caught being wrong.
pub fn gnu_no_byte_compile_marker_line(line: &str) -> bool {
    if !line.starts_with(';') {
        return false;
    }

    let needle = "no-byte-compile:";
    let mut search_from = 0;
    while let Some(relative_index) = line[search_from..].find(needle) {
        let index = search_from + relative_index;
        // `.*` starts after the anchored `;`, so the `[^a-zA-Z]` it is
        // followed by lands at index 1 at the earliest.
        let preceded_by_non_letter = index >= 2
            && line[..index]
                .chars()
                .next_back()
                .is_some_and(|ch| !ch.is_ascii_alphabetic());
        if preceded_by_non_letter
            && line[index + needle.len()..]
                .trim_start_matches(' ')
                .starts_with('t')
        {
            return true;
        }
        search_from = index + needle.len();
    }

    false
}

/// Whether this source exempts itself from byte-compilation, GNU's way.
pub fn source_declares_no_byte_compile(source: &Path) -> io::Result<bool> {
    let contents = std::fs::read(source)?;
    let contents = String::from_utf8_lossy(&contents);
    Ok(contents.lines().any(gnu_no_byte_compile_marker_line))
}

/// What one whole Lisp tree looks like against GNU's rule.
///
/// The counters are not decoration.  Ledger 206 published a green guard that
/// had been green before the fix, and ledger 205's brief records a suite that
/// reported `ok` having run zero tests; a scan that silently examined nothing
/// is the same failure.  A caller asserts on [`Self::missing`] **and** on
/// [`Self::examined`].
#[derive(Clone, Debug, Default, Eq, PartialEq)]
pub struct LispBytecodeCoverage {
    /// Every `.el` the scan read, exempt or not.
    pub examined: usize,
    /// Sources with a `.elc` beside them.
    pub compiled: usize,
    /// Sources GNU also ships without a `.elc`, because they say so.
    pub exempt: Vec<PathBuf>,
    /// Sources GNU would have compiled and this tree has not.  The defect.
    pub missing: Vec<PathBuf>,
}

impl LispBytecodeCoverage {
    /// Walk ROOT and answer GNU's question of every `.el` under it.
    ///
    /// Symlinked directories are followed the way `find` does by default --
    /// they are not -- and dotfiles are skipped, matching GNU's
    /// `! -name '.*'`.
    pub fn scan(root: &Path) -> io::Result<Self> {
        let mut sources = Vec::new();
        collect_lisp_sources(root, &mut sources)?;
        sources.sort();

        let mut coverage = Self::default();
        for source in sources {
            coverage.examined += 1;
            match BytecodeCoverage::of(&source)? {
                BytecodeCoverage::Compiled { .. } => coverage.compiled += 1,
                BytecodeCoverage::ExemptBySourceCookie => coverage.exempt.push(source),
                BytecodeCoverage::MissingBytecode => coverage.missing.push(source),
            }
        }
        Ok(coverage)
    }

    /// A one-screen report, for a failure message that does not need a second
    /// command to be actionable.
    pub fn describe(&self, root: &Path) -> String {
        let mut out = format!(
            "{}: {} .el examined, {} with a .elc, {} exempt by their own \
             `no-byte-compile: t', {} MISSING bytecode",
            root.display(),
            self.examined,
            self.compiled,
            self.exempt.len(),
            self.missing.len()
        );
        for source in &self.missing {
            out.push_str("\n  missing .elc: ");
            out.push_str(&source.display().to_string());
        }
        out
    }
}

fn collect_lisp_sources(current: &Path, out: &mut Vec<PathBuf>) -> io::Result<()> {
    let entries = match std::fs::read_dir(current) {
        Ok(entries) => entries,
        Err(err) if err.kind() == io::ErrorKind::NotFound => return Ok(()),
        Err(err) => return Err(err),
    };

    for entry in entries {
        let entry = entry?;
        let path = entry.path();
        let name = entry.file_name();
        let name = name.to_string_lossy();
        if name.starts_with('.') {
            continue;
        }
        let file_type = entry.file_type()?;
        if file_type.is_dir() {
            collect_lisp_sources(&path, out)?;
        } else if file_type.is_file() && path.extension().is_some_and(|ext| ext == "el") {
            out.push(path);
        }
    }

    Ok(())
}

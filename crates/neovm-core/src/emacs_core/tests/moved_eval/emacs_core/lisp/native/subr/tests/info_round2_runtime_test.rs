use crate::emacs_core::subr_info::builtin_subr_arity_1;
use neovm_eval::emacs_core::eval::SubrValueExt;
use neovm_value::error::FlowResultExt as _;

fn assert_subr_arity(name: &str, min: i64, max: Option<i64>) {
    let mut ctx = crate::test_utils::new_context();
    let function = ctx
        .obarray()
        .symbol_function(name)
        .unwrap_or_else(|| panic!("{name} must have a registered function cell"));
    assert!(function.is_subr(), "{name} must be registered as a subr");
    let result = builtin_subr_arity_1(&mut ctx, function).unwrap();
    if result.is_cons() {
        let pair_car = result.cons_car();
        let pair_cdr = result.cons_cdr();
        assert_eq!(
            pair_car.as_int(),
            Some(min),
            "subr min arity mismatch for {name}"
        );
        match max {
            Some(n) => assert_eq!(
                pair_cdr.as_int(),
                Some(n),
                "subr max arity mismatch for {name}"
            ),
            None => assert_eq!(
                pair_cdr.as_bare_symbol_name(),
                Some("many"),
                "subr max arity mismatch for {name}"
            ),
        }
    } else {
        panic!("expected cons cell");
    }
}


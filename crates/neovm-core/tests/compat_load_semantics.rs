mod common;

use std::fs;

use common::{elisp_string, oracle_enabled, run_neovm_eval, run_oracle_eval};

struct LoadCase {
    name: &'static str,
    form: String,
}

#[test]
fn compat_load_semantics_matches_gnu_emacs() {
    if !oracle_enabled() {
        eprintln!(
            "skipping load semantics audit: set NEOVM_FORCE_ORACLE_PATH or place GNU Emacs mirror alongside the repo"
        );
        return;
    }

    let fixture_dir = tempfile::tempdir().expect("load semantics tempdir");

    let context_path = fixture_dir.path().join("load-context.el");
    fs::write(
        &context_path,
        ";; -*- lexical-binding: t; -*-\n(list load-file-name load-in-progress lexical-binding)\n",
    )
    .expect("write load-context fixture");

    let history_path = fixture_dir.path().join("load-history.el");
    fs::write(
        &history_path,
        ";; -*- lexical-binding: t; -*-\n'load-history-body\n",
    )
    .expect("write load-history fixture");

    let hook_path = fixture_dir.path().join("load-hook.el");
    fs::write(
        &hook_path,
        ";; -*- lexical-binding: t; -*-\n(setq neovm--load-body 'file-body)\n'body-ran\n",
    )
    .expect("write load-hook fixture");

    let generated_loaddefs_path = fixture_dir.path().join("generated-loaddefs.el");
    fs::write(
        &generated_loaddefs_path,
        ";;; loaddefs.el --- automatically extracted autoloads (do not edit)   -*- lexical-binding: t -*-\n\
;; Generated by the `loaddefs-generate' function.\n\
\n\
(defvar-local vm-generated-local 7 \"Generated local.\")\n",
    )
    .expect("write generated loaddefs fixture");

    let generated_metadata_path = fixture_dir.path().join("generated-metadata-loaddefs.el");
    fs::write(
        &generated_metadata_path,
        ";;; loaddefs.el --- automatically extracted autoloads (do not edit)   -*- lexical-binding: t -*-\n\
;; Generated by the `loaddefs-generate' function.\n\
\n\
(autoload 'vm-generated-fn \"vm-generated\" \"Doc.\" t)\n\
(register-definition-prefixes \"vm-generated\" '(\"vm-generated-\"))\n\
(defvar vm-generated-option nil \"Generated option.\")\n\
(custom-autoload 'vm-generated-option \"vm-generated\" t)\n\
(put 'vm-generated-option 'safe-local-variable #'symbolp)\n\
(function-put 'vm-generated-fn 'interactive-only 'vm-generated-target)\n\
(define-obsolete-function-alias 'vm-generated-old #'vm-generated-fn \"31.1\" \"Old doc.\")\n\
",
    )
    .expect("write generated metadata loaddefs fixture");

    let chained_autoload_outer_path = fixture_dir.path().join("vm-chain-outer.el");
    fs::write(
        &chained_autoload_outer_path,
        "(autoload 'vm-chain-run \"vm-chain-target\" nil t)\n",
    )
    .expect("write chained autoload outer fixture");

    let chained_autoload_target_path = fixture_dir.path().join("vm-chain-target.el");
    fs::write(
        &chained_autoload_target_path,
        "(defalias 'vm-chain-run #'(lambda (value) (+ value 7)))\n",
    )
    .expect("write chained autoload target fixture");

    let removed_autoload_path = fixture_dir.path().join("vm-chain-removes-definition.el");
    fs::write(&removed_autoload_path, "(fmakunbound 'vm-chain-removed)\n")
        .expect("write autoload removal fixture");

    let late_interactive_autoload_path = fixture_dir.path().join("vm-ci-late-command.el");
    fs::write(
        &late_interactive_autoload_path,
        "(defalias 'vm-ci-late-command
           #'(lambda () (interactive) 'loaded-command))\n",
    )
    .expect("write call-interactively autoload fixture");

    let recursive_path = fixture_dir.path().join("recursive-load.el");
    fs::write(
        &recursive_path,
        format!(
            ";; -*- lexical-binding: t; -*-\n(load {} nil nil t)\n",
            elisp_string(&recursive_path)
        ),
    )
    .expect("write recursive-load fixture");

    let missing_path = fixture_dir.path().join("missing-load.el");

    let utf8_emacs_path = fixture_dir.path().join("load-utf8-emacs.el");
    let mut utf8_emacs_source =
        b";; -*- coding: utf-8-emacs; lexical-binding: t; -*-\n(setq neovm--utf8-emacs-probe ?"
            .to_vec();
    utf8_emacs_source.extend_from_slice(&[0xF6, 0xA0, 0x87, 0x8A]);
    utf8_emacs_source.extend_from_slice(b")\n");
    fs::write(&utf8_emacs_path, utf8_emacs_source).expect("write utf-8-emacs load fixture");

    let cases = vec![
        LoadCase {
            name: "load_context_visibility",
            form: format!("(load {} nil nil t)", elisp_string(&context_path)),
        },
        LoadCase {
            name: "load_noerror_missing_file",
            form: format!("(load {} t nil t)", elisp_string(&missing_path)),
        },
        LoadCase {
            name: "load_history_pushes_entry",
            form: format!(
                r#"(let ((before load-history))
  (load {path} nil nil t)
  (let ((entry (car load-history)))
    (list (equal before (cdr load-history))
          (consp entry)
          (equal (car entry) {path}))))"#,
                path = elisp_string(&history_path)
            ),
        },
        LoadCase {
            name: "load_source_file_function_intercepts_source",
            form: format!(
                r#"(setq neovm--load-intercept-args nil
       neovm--load-body nil)
(let ((load-source-file-function
       (lambda (fullname file noerror nomessage)
         (setq neovm--load-intercept-args
               (list fullname file noerror nomessage))
         'intercepted)))
  (list (load {path} nil nil t)
        neovm--load-intercept-args
        neovm--load-body))"#,
                path = elisp_string(&hook_path)
            ),
        },
        LoadCase {
            name: "recursive_load_cycle_limit",
            form: format!(
                r#"(condition-case err
    (load {path} nil nil t)
  (error (car err)))"#,
                path = elisp_string(&recursive_path)
            ),
        },
        LoadCase {
            name: "generated_loaddefs_use_gnu_defvar_local_macro",
            form: format!(
                r#"(progn
  (load {path} nil nil t)
  (let ((buf (generate-new-buffer " *vm-generated-local*")))
    (unwind-protect
        (list (macrop 'defvar-local)
              (default-boundp 'vm-generated-local)
              (default-value 'vm-generated-local)
              (with-current-buffer buf
                (setq vm-generated-local 19)
                (list (local-variable-p 'vm-generated-local)
                      vm-generated-local
                      (default-value 'vm-generated-local))))
      (kill-buffer buf))))"#,
                path = elisp_string(&generated_loaddefs_path)
            ),
        },
        LoadCase {
            name: "generated_loaddefs_runtime_metadata_matches_gnu",
            form: format!(
                r#"(progn
  (load {path} nil nil t)
  (list (autoloadp (symbol-function 'vm-generated-fn))
        (gethash "vm-generated-" definition-prefixes)
        (get 'vm-generated-option 'custom-autoload)
        (get 'vm-generated-option 'custom-loads)
        (get 'vm-generated-option 'safe-local-variable)
        (get 'vm-generated-fn 'interactive-only)
        (symbol-function 'vm-generated-old)
        (get 'vm-generated-old 'byte-obsolete-info)
        (get 'vm-generated-old 'function-documentation)))"#,
                path = elisp_string(&generated_metadata_path)
            ),
        },
        LoadCase {
            name: "autoload_definitions_are_recorded_in_load_history",
            form: format!(
                r#"(let ((load-history nil))
  (load {path} nil nil t)
  (let ((entry (car load-history)))
    (list (and (member '(defun . vm-generated-fn) entry) t)
          (and (member '(defun . vm-generated-old) entry) t))))"#,
                path = elisp_string(&generated_metadata_path)
            ),
        },
        LoadCase {
            name: "named_call_follows_chained_autoloads",
            form: format!(
                r#"(let ((load-path (cons {directory} load-path)))
  (autoload 'vm-chain-run "vm-chain-outer" nil t)
  (funcall 'vm-chain-run 5))"#,
                directory = elisp_string(fixture_dir.path())
            ),
        },
        LoadCase {
            name: "named_call_retries_to_void_after_autoload_removes_definition",
            form: format!(
                r#"(let ((load-path (cons {directory} load-path)))
  (autoload 'vm-chain-removed "vm-chain-removes-definition" nil t)
  (condition-case error
      (funcall 'vm-chain-removed)
    (error error)))"#,
                directory = elisp_string(fixture_dir.path())
            ),
        },
        LoadCase {
            name: "call_interactively_propagates_noninteractive_autoload_failure",
            form: r#"(progn
  (autoload 'vm-ci-missing-plain "vm-ci-missing-plain-library" nil nil)
  (condition-case error
      (call-interactively 'vm-ci-missing-plain)
    (error (car error))))"#
                .to_owned(),
        },
        LoadCase {
            name: "call_interactively_loads_before_testing_command_status",
            form: format!(
                r#"(let ((load-path (cons {directory} load-path)))
  (autoload 'vm-ci-late-command "vm-ci-late-command" nil nil)
  (call-interactively 'vm-ci-late-command))"#,
                directory = elisp_string(fixture_dir.path())
            ),
        },
        LoadCase {
            name: "call_interactively_obtains_the_interactive_form_once",
            form: r#"(let ((original (symbol-function 'interactive-form))
       (calls 0))
  (unwind-protect
      (progn
        (fset 'interactive-form
              (lambda (command)
                (setq calls (1+ calls))
                (funcall original command)))
        (fset 'vm-ci-single-form
              (lambda (value) (interactive (list 9)) value))
        (list (call-interactively 'vm-ci-single-form) calls))
    (fset 'interactive-form original)
    (fmakunbound 'vm-ci-single-form)))"#
                .to_owned(),
        },
        LoadCase {
            name: "call_interactively_accepts_symbol_interactive_form_property",
            form: r#"(progn
  (fset 'vm-ci-property-command (lambda (value) value))
  (put 'vm-ci-property-command
       'interactive-form
       '(interactive (list 9)))
  (unwind-protect
      (call-interactively 'vm-ci-property-command)
    (fmakunbound 'vm-ci-property-command)))"#
                .to_owned(),
        },
        LoadCase {
            name: "region_subr_interactive_form_matches_gnu",
            form: "(interactive-form 'upcase-region)".to_owned(),
        },
        LoadCase {
            name: "load_with_code_conversion_preserves_utf_8_emacs_chars",
            form: format!(
                r#"(let ((sym 'neovm--utf8-emacs-probe))
  (when (boundp sym)
    (makunbound sym))
  (load {path} nil nil t)
  (let ((value (symbol-value sym)))
    (list (characterp value)
          (= value #x1A01CA))))"#,
                path = elisp_string(&utf8_emacs_path)
            ),
        },
    ];

    for case in cases {
        let gnu = run_oracle_eval(&case.form).expect("GNU Emacs evaluation");
        let neovm = run_neovm_eval(&case.form).expect("NeoVM evaluation");
        assert_eq!(
            neovm, gnu,
            "load semantics mismatch for {}:\nGNU: {}\nNeoVM: {}",
            case.name, gnu, neovm
        );
    }
}

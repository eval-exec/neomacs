/// Expand a `$(doc_obj)` object list for one profile.
fn expand_objects(
    tokens: &[&str],
    base_tokens: &[&str],
    profile: Profile,
    src_dir: &Path,
    out: &mut Vec<String>,
) -> Result<(), String> {
    for token in tokens {
        if let Some(variable) = token.strip_prefix("$(").and_then(|t| t.strip_suffix(')')) {
            let objects: Vec<String> = if variable == "base_obj" {
                let mut nested = Vec::new();
                expand_objects(base_tokens, base_tokens, profile, src_dir, &mut nested)?;
                nested
            } else {
                variable_objects(variable, profile)?
                    .into_iter()
                    .map(str::to_string)
                    .collect()
            };
            out.extend(objects);
        } else {
            out.push((*token).to_string());
        }
    }
    Ok(())
}

/// The `DOC` object list for one profile, as source file names.
fn profile_objects(src_dir: &Path, profile: Profile) -> Result<Vec<String>, String> {
    let makefile_path = src_dir.join("Makefile.in");
    let text = fs::read_to_string(&makefile_path)
        .map_err(|error| format!("read {}: {error}", makefile_path.display()))?;
    let base = makefile_variable(&text, "base_obj")?;
    let doc = makefile_variable(&text, "doc_obj")?;
    let base_tokens: Vec<&str> = base.split_whitespace().collect();
    let doc_tokens: Vec<&str> = doc.split_whitespace().collect();
    let mut objects = Vec::new();
    expand_objects(&doc_tokens, &base_tokens, profile, src_dir, &mut objects)?;
    let mut sources = Vec::new();
    for object in objects {
        let stem = object
            .strip_suffix(".o")
            .ok_or_else(|| format!("Makefile object `{object}` is not a `.o`"))?;
        let mut found = None;
        for extension in ["c", "m", "cc"] {
            let candidate = src_dir.join(format!("{stem}.{extension}"));
            if candidate.is_file() {
                found = Some(format!("{stem}.{extension}"));
                break;
            }
        }
        let source = found.ok_or_else(|| {
            format!(
                "object `{object}` has no source file in {}; the profile model needs an update",
                src_dir.display()
            )
        })?;
        sources.push(source);
    }
    Ok(sources)
}

/// The source files a reference profile compiles, in the order
/// `make-docfile` receives them (`$(doc_obj)`).
fn profile_scan_order(src_dir: &Path, profile: Profile) -> Result<Vec<String>, String> {
    let mut ordered: Vec<String> = Vec::new();
    for source in profile_objects(src_dir, profile)? {
        if !ordered.contains(&source) {
            ordered.push(source);
        }
    }
    Ok(ordered)
}

/// Read every `DEFSYM (Qname, "spelling")` occurrence in one GNU source file.
/// One literal `intern_c_string ("...")` / `intern ("...")` spelling.
///
/// GNU's C startup code interns these names directly (`Fprovide`, font style
/// tables, X cursor and DND tables, ...), so they are obarray members in every
/// build that compiles the literal, independently of `DEFSYM`. The DEFSYM
/// ledger cannot see them: `DEFSYM` marks a `syms_of_*` declaration, while the
/// `intern_c_string` call is an ordinary C expression in the same file.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct CInternRow {
    pub name: String,
    /// The profiles compiling a source that carries the literal.
    pub gate: ProfileMask,
    /// The first scanned source carrying it.
    pub source: String,
}

fn c_ident_start(byte: u8) -> bool {
    byte.is_ascii_alphabetic() || byte == b'_'
}

fn c_ident_continue(byte: u8) -> bool {
    byte.is_ascii_alphanumeric() || byte == b'_'
}

/// Parse one C string literal starting at the opening quote; returns the
/// decoded bytes and the index one past the closing quote.
fn parse_c_string(bytes: &[u8], start: usize) -> Option<(Vec<u8>, usize)> {
    let mut out = Vec::new();
    let mut index = start + 1;
    while index < bytes.len() {
        match bytes[index] {
            b'"' => return Some((out, index + 1)),
            b'\\' => {
                index += 1;
                let escape = *bytes.get(index)?;
                match escape {
                    b'n' => out.push(b'\n'),
                    b't' => out.push(b'\t'),
                    b'r' => out.push(b'\r'),
                    b'\\' => out.push(b'\\'),
                    b'"' => out.push(b'"'),
                    b'\'' => out.push(b'\''),
                    b'0'..=b'7' => {
                        let mut value = 0u32;
                        let mut digits = 0;
                        while digits < 3 {
                            match bytes.get(index) {
                                Some(digit @ b'0'..=b'7') => {
                                    value = value * 8 + u32::from(digit - b'0');
                                    index += 1;
                                    digits += 1;
                                }
                                _ => break,
                            }
                        }
                        index -= 1;
                        out.push(u8::try_from(value).ok()?);
                    }
                    b'x' => {
                        let mut value = 0u32;
                        let mut digits = 0;
                        while digits < 2 {
                            match bytes.get(index + 1) {
                                Some(digit) if digit.is_ascii_hexdigit() => {
                                    value = value * 16
                                        + u32::from((*digit as char).to_digit(16).unwrap());
                                    index += 1;
                                    digits += 1;
                                }
                                _ => break,
                            }
                        }
                        out.push(u8::try_from(value).ok()?);
                    }
                    other => out.push(other),
                }
                index += 1;
            }
            byte => {
                out.push(byte);
                index += 1;
            }
        }
    }
    None
}

/// Collect the literal intern spellings of one C source.
///
/// Comments, string contents and character literals are skipped so only real
/// call sites contribute; the spellings themselves must be ASCII because a
/// Lisp symbol name that survives the C string is what `intern` receives.
fn scan_c_intern_literals(bytes: &[u8], out: &mut Vec<String>) {
    let mut index = 0;
    while index < bytes.len() {
        match bytes[index] {
            b'/' if bytes.get(index + 1) == Some(&b'/') => {
                while index < bytes.len() && bytes[index] != b'\n' {
                    index += 1;
                }
            }
            b'/' if bytes.get(index + 1) == Some(&b'*') => {
                index += 2;
                while index + 1 < bytes.len() && !(bytes[index] == b'*' && bytes[index + 1] == b'/')
                {
                    index += 1;
                }
                index = (index + 2).min(bytes.len());
            }
            quote @ (b'"' | b'\'') => {
                index += 1;
                while index < bytes.len() {
                    match bytes[index] {
                        b'\\' => index += 2,
                        byte if byte == quote => {
                            index += 1;
                            break;
                        }
                        _ => index += 1,
                    }
                }
            }
            byte if c_ident_start(byte) => {
                let start = index;
                while index < bytes.len() && c_ident_continue(bytes[index]) {
                    index += 1;
                }
                let identifier = &bytes[start..index];
                let is_intern = identifier == b"intern" || identifier == b"intern_c_string";
                // `Fintern`/`intern_soft` must not match: the boundary check
                // above already rejects the former (leading `F`), and the
                // identifier comparison rejects the latter.
                if !is_intern {
                    continue;
                }
                let mut cursor = index;
                while cursor < bytes.len() && bytes[cursor].is_ascii_whitespace() {
                    cursor += 1;
                }
                if bytes.get(cursor) != Some(&b'(') {
                    continue;
                }
                cursor += 1;
                while cursor < bytes.len() && bytes[cursor].is_ascii_whitespace() {
                    cursor += 1;
                }
                if bytes.get(cursor) != Some(&b'"') {
                    continue;
                }
                if let Some((literal, end)) = parse_c_string(bytes, cursor)
                    && literal.is_ascii()
                    && !literal.is_empty()
                {
                    out.push(String::from_utf8(literal).expect("ASCII checked"));
                    index = end;
                }
            }
            _ => index += 1,
        }
    }
}

/// The brace-matched bodies of every `syms_of_*` function in one source.
///
/// GNU interns a C literal at startup only when the call runs from the
/// `syms_of_*` function `src/emacs.c` dispatches. A literal in a runtime
/// helper (`print_object`'s `escape-newlines`, `process.c`'s
/// `broadcast`/`loopback`) is a name GNU interns only when that code runs,
/// not an obarray member of the dumped image. Restricting the scan to the
/// `syms_of_*` bodies is what keeps this ledger a startup membership table.
fn syms_of_bodies(bytes: &[u8]) -> Vec<(usize, usize)> {
    let mut bodies = Vec::new();
    let mut index = 0;
    while index + 7 < bytes.len() {
        if bytes[index..].starts_with(b"syms_of_")
            && (index == 0 || !c_ident_continue(bytes[index - 1]))
        {
            let mut cursor = index + "syms_of_".len();
            while cursor < bytes.len() && c_ident_continue(bytes[cursor]) {
                cursor += 1;
            }
            // Skip whitespace and the parameter list.
            while cursor < bytes.len() && bytes[cursor].is_ascii_whitespace() {
                cursor += 1;
            }
            if bytes.get(cursor) != Some(&b'(') {
                index = cursor.max(index + 1);
                continue;
            }
            let mut depth = 0usize;
            while cursor < bytes.len() {
                match bytes[cursor] {
                    b'(' => depth += 1,
                    b')' => {
                        depth -= 1;
                        if depth == 0 {
                            cursor += 1;
                            break;
                        }
                    }
                    _ => {}
                }
                cursor += 1;
            }
            while cursor < bytes.len() && bytes[cursor] != b'{' {
                cursor += 1;
            }
            if cursor >= bytes.len() {
                break;
            }
            let start = cursor + 1;
            let mut depth = 1usize;
            cursor = start;
            while cursor < bytes.len() && depth > 0 {
                match bytes[cursor] {
                    b'{' => depth += 1,
                    b'}' => depth -= 1,
                    b'"' => {
                        cursor += 1;
                        while cursor < bytes.len() {
                            match bytes[cursor] {
                                b'\\' => cursor += 2,
                                b'"' => break,
                                _ => cursor += 1,
                            }
                        }
                    }
                    _ => {}
                }
                cursor += 1;
            }
            bodies.push((start, cursor.min(bytes.len())));
            index = cursor;
        } else {
            index += 1;
        }
    }
    bodies
}

/// Every literal C intern spelling of the reference profiles.
pub fn extract_c_interns(src_dir: &Path) -> Result<Vec<CInternRow>, String> {
    let scan_orders: Vec<(Profile, Vec<String>)> = Profile::ALL
        .into_iter()
        .map(|profile| Ok((profile, profile_scan_order(src_dir, profile)?)))
        .collect::<Result<_, String>>()?;
    let mut per_file: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for (_, order) in &scan_orders {
        for file in order {
            if per_file.contains_key(file) {
                continue;
            }
            let path = src_dir.join(file);
            let bytes =
                fs::read(&path).map_err(|error| format!("read {}: {error}", path.display()))?;
            let mut spellings = Vec::new();
            for (start, end) in syms_of_bodies(&bytes) {
                scan_c_intern_literals(&bytes[start..end], &mut spellings);
            }
            per_file.insert(file.clone(), spellings);
        }
    }
    let mut rows: BTreeMap<String, CInternRow> = BTreeMap::new();
    for (profile, order) in &scan_orders {
        for file in order {
            let Some(spellings) = per_file.get(file) else {
                continue;
            };
            for name in spellings {
                let entry = rows.entry(name.clone()).or_insert_with(|| CInternRow {
                    name: name.clone(),
                    gate: ProfileMask::NONE,
                    source: file.clone(),
                });
                entry.gate = entry.gate.union(ProfileMask(profile.bit()));
            }
        }
    }
    let mut rows: Vec<CInternRow> = rows.into_values().collect();
    rows.sort_by(|left, right| {
        left.source
            .cmp(&right.source)
            .then_with(|| left.name.cmp(&right.name))
    });
    Ok(rows)
}

/// Three-valued preprocessor truth for one profile's reference build.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Tri {
    True,
    False,
    Unknown,
}


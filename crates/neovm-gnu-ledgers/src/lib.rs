/// Build profiles the gates are keyed by.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum Profile {
    Linux,
    Macos,
    Windows,
}

impl Profile {
    pub const ALL: [Profile; 3] = [Profile::Linux, Profile::Macos, Profile::Windows];

    const fn bit(self) -> u8 {
        match self {
            Profile::Linux => 1,
            Profile::Macos => 2,
            Profile::Windows => 4,
        }
    }

    pub const fn name(self) -> &'static str {
        match self {
            Profile::Linux => "linux",
            Profile::Macos => "macos",
            Profile::Windows => "windows",
        }
    }
}

/// A set of build profiles.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ProfileMask(u8);

impl ProfileMask {
    pub const NONE: Self = Self(0);

    pub const fn union(self, other: Self) -> Self {
        Self(self.0 | other.0)
    }

    pub const fn is_empty(self) -> bool {
        self.0 == 0
    }

    pub const fn contains(self, profile: Profile) -> bool {
        self.0 & profile.bit() != 0
    }

    fn names(self) -> String {
        let mut parts = Vec::new();
        for profile in Profile::ALL {
            if self.0 & profile.bit() != 0 {
                parts.push(profile.name());
            }
        }
        if parts.is_empty() {
            "none".to_string()
        } else {
            parts.join("+")
        }
    }

    fn parse(text: &str) -> Option<Self> {
        if text == "none" {
            return Some(Self::NONE);
        }
        let mut mask = Self::NONE;
        for part in text.split('+') {
            let profile = Profile::ALL
                .into_iter()
                .find(|profile| profile.name() == part)?;
            mask = mask.union(Self(profile.bit()));
        }
        Some(mask)
    }
}

/// The profile decision for one spelling.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Gate {
    Profiles(ProfileMask),
    Uninterned,
}

impl Gate {
    pub fn as_str(self) -> String {
        match self {
            Gate::Profiles(mask) => mask.names(),
            Gate::Uninterned => "uninterned".to_string(),
        }
    }

    fn parse(text: &str) -> Option<Self> {
        if text == "uninterned" {
            return Some(Self::Uninterned);
        }
        ProfileMask::parse(text).map(Self::Profiles)
    }

    /// Whether the generated table carries this row at all.
    pub const fn is_emitted(self) -> bool {
        match self {
            Gate::Profiles(mask) => !mask.is_empty(),
            Gate::Uninterned => false,
        }
    }

    fn mask(self) -> ProfileMask {
        match self {
            Gate::Profiles(mask) => mask,
            Gate::Uninterned => ProfileMask::NONE,
        }
    }
}

/// One distinct DEFSYM spelling and the decision to intern it at boot.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Row {
    /// The Lisp spelling (`DEFSYM`'s second argument).
    pub name: String,
    /// The profiles that compile a source defining this spelling.
    pub gate: Gate,
    /// The C `Q...` identifier (make-docfile's sort key).
    pub c_name: String,
    /// The GNU source file the row's gate is derived from.
    pub source: String,
}


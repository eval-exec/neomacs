//! Generator for the GNU DEFSYM boot-membership table.
//!
//! GNU 31.1's `DEFSYM` is an empty placeholder macro (`src/lisp.h:2395`,
//! "Placeholder for make-docfile to process"; the real definition is done by
//! lread.c's `define_symbol`). The symbols it names live in the generated
//! `defsym_name[]` / `lispsym` arrays (`src/globals.h`, written by
//! `make-docfile -g`), and `init_obarray_once` (`src/lread.c:5193-5203`)
//! interns every one of them into the initial obarray before any Lisp runs.
//! A spelling that a build compiled in therefore exists in `(obarray)` with no
//! function, no value and an empty plist, which is why e.g.
//! `(intern-soft "buffer-or-string-p")` is a symbol in GNU and was missing
//! here.
//!
//! ## Which spellings a build compiles in
//!
//! `make-docfile -g` is handed `$(doc_obj)` (`src/Makefile.in:470-471`,
//! `:682-684`), so the set is the object list of the configuration, not the
//! union of the source tree. This module reads that list out of the pinned
//! `src/Makefile.in`, expands every `$(VAR)` from the configuration model
//! below, and maps each object to its source file. The model records what
//! `configure.ac` puts in each variable for the three reference profiles:
//!
//! * `linux` - the attested oracle configuration (`--with-x-toolkit=gtk3
//!   --without-pgtk --with-tree-sitter --with-dbus --with-native-compilation=no
//!   ...`, see `scripts/ci/build-gnu-oracle.sh`).
//! * `macos` - the NextStep profile of the same script (`--with-ns
//!   --disable-ns-self-contained --without-x`).
//! * `windows` - the MinGW-w64 `HAVE_W32` build.
//!
//! Each spelling's gate is the set of profiles whose object list contains a
//! file that `DEFSYM`s it. `kqueue.c`, for example, is the BSD/macOS
//! `NOTIFY_OBJ` (`configure.ac:4148-4162`) and is therefore macOS-only, while
//! the Linux `NOTIFY_OBJ` is `inotify.o` (`configure.ac:4128-4140`).
//!
//! ## Order
//!
//! `make-docfile.c:638-667` sorts the symbol globals by the C `Q...`
//! identifier: `Qnil Q t Qunbound Qerror Qlambda` first ("common symbols in
//! decreasing popularity order"), then `strcmp` of the identifier. GNU interns
//! in exactly that order, and the obarray completion order reverses insertion
//! within a hash bucket, so the table keeps it byte-for-byte.
//!
//! ## Never interned
//!
//! Six spellings are compiled but not in the startup obarray: `unbound`
//! (`define_symbol` skips `Qunbound`, `src/lread.c:4762-4771`) and the five
//! startup `Funintern`s (`src/lread.c:5872-5873`, `src/editfns.c:4866`,
//! `src/eval.c:4597`, `src/print.c:3063`). Their rows say `uninterned` and the
//! generator refuses to emit them.
//!
//! Regenerate with `cargo xtask gnu-defsyms --source <GNU checkout>`; verify
//! with `--check` (add `--source` to also re-check the ledger against the
//! pinned source).


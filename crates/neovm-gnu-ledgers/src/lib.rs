/// `make-docfile`'s popularity ranking (`lib-src/make-docfile.c:649-663`).
fn common_symbol_rank(c_name: &str) -> u8 {
    match c_name {
        "Qnil" => 0,
        "Qt" => 1,
        "Qunbound" => 2,
        "Qerror" => 3,
        "Qlambda" => 4,
        _ => u8::MAX,
    }
}

/// The make-docfile ordering key: commonsym rank, then `strcmp` of the C
/// identifier.
pub fn sort_key(row: &Row) -> (u8, &str) {
    (common_symbol_rank(&row.c_name), row.c_name.as_str())
}

/// Read one `name = value` assignment out of `src/Makefile.in`, joining its
/// backslash continuations.
fn makefile_variable(text: &str, name: &str) -> Result<String, String> {
    let mut lines = text.lines();
    let mut value: Option<String> = None;
    while let Some(line) = lines.next() {
        let Some(rest) = line.strip_prefix(name) else {
            continue;
        };
        let Some(rest) = rest.trim_start().strip_prefix('=') else {
            continue;
        };
        let mut joined = rest.trim().to_string();
        while joined.ends_with('\\') && value.is_none() {
            joined.pop();
            match lines.next() {
                Some(next) => {
                    joined.push(' ');
                    joined.push_str(next.trim());
                }
                None => break,
            }
        }
        value = Some(joined);
        break;
    }
    value.ok_or_else(|| format!("src/Makefile.in has no `{name} =` assignment"))
}


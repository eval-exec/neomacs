fn parse_c_intern_ledger_with(text: &str, ledger: &str) -> Result<Vec<CInternRow>, String> {
    let mut rows = Vec::new();
    for (line_number, line) in text.lines().enumerate() {
        if line.trim().is_empty() || line.starts_with('#') {
            continue;
        }
        let fields: Vec<&str> = line.split('\t').collect();
        if fields.len() != 3 {
            return Err(format!(
                "{}:{}: expected name<TAB>gate<TAB>source",
                ledger,
                line_number + 1
            ));
        }
        let gate = ProfileMask::parse(fields[1]).ok_or_else(|| {
            format!(
                "{}:{}: unknown profile gate `{}`",
                ledger,
                line_number + 1,
                fields[1]
            )
        })?;
        rows.push(CInternRow {
            name: fields[0].to_string(),
            gate,
            source: fields[2].to_string(),
        });
    }
    Ok(rows)
}

fn scan_source(text: &str, out: &mut Vec<(String, String)>) {
    let bytes = text.as_bytes();
    for (offset, _) in text.match_indices("DEFSYM") {
        // A real DEFSYM token: not the tail of a longer identifier.
        if offset > 0 && (bytes[offset - 1].is_ascii_alphanumeric() || bytes[offset - 1] == b'_') {
            continue;
        }
        let mut cursor = offset + "DEFSYM".len();
        let skip_ws = |cursor: &mut usize| {
            while *cursor < bytes.len() && bytes[*cursor].is_ascii_whitespace() {
                *cursor += 1;
            }
        };
        skip_ws(&mut cursor);
        if bytes.get(cursor) != Some(&b'(') {
            continue;
        }
        cursor += 1;
        skip_ws(&mut cursor);
        let ident_start = cursor;
        while cursor < bytes.len()
            && (bytes[cursor].is_ascii_alphanumeric() || bytes[cursor] == b'_')
        {
            cursor += 1;
        }
        let c_name = &text[ident_start..cursor];
        if !c_name.starts_with('Q') {
            continue;
        }
        skip_ws(&mut cursor);
        if bytes.get(cursor) != Some(&b',') {
            continue;
        }
        cursor += 1;
        skip_ws(&mut cursor);
        if bytes.get(cursor) != Some(&b'"') {
            continue;
        }
        cursor += 1;
        let mut name = String::new();
        let mut closed = false;
        while cursor < bytes.len() {
            match bytes[cursor] {
                b'\\' => {
                    let escaped = bytes.get(cursor + 1).copied();
                    match escaped {
                        Some(b'"') => name.push('"'),
                        Some(b'\\') => name.push('\\'),
                        Some(other) => {
                            // No DEFSYM spelling in the pinned source needs
                            // another escape; keep the byte so drift is loud
                            // in the ledger instead of silently normalised.
                            name.push(other as char);
                        }
                        None => break,
                    }
                    cursor += 2;
                }
                b'"' => {
                    closed = true;
                    break;
                }
                byte => {
                    name.push(byte as char);
                    cursor += 1;
                }
            }
        }
        if !closed || name.is_empty() {
            continue;
        }
        out.push((c_name.to_string(), name));
    }
}

/// Extract the ledger rows from the pinned GNU `src` directory.
pub fn extract(src_dir: &Path) -> Result<Vec<Row>, String> {
    // make-docfile is handed `$(doc_obj)` in makefile order and merges
    // duplicate C identifiers keeping the first spelling it reads, so the
    // same identifier can resolve to different spellings per profile
    // (`Qstatic_gray` is "static-gray" in `xfns.c` and "static-color" in
    // `androidfns.c`). Keep each profile's scan order.
    let scan_orders: Vec<(Profile, Vec<String>)> = Profile::ALL
        .into_iter()
        .map(|profile| Ok((profile, profile_scan_order(src_dir, profile)?)))
        .collect::<Result<_, String>>()?;

    let entries =
        fs::read_dir(src_dir).map_err(|error| format!("read {}: {error}", src_dir.display()))?;
    let mut files: Vec<PathBuf> = entries
        .filter_map(|entry| entry.ok().map(|entry| entry.path()))
        .filter(|path| {
            matches!(
                path.extension().and_then(|extension| extension.to_str()),
                Some("c") | Some("m")
            )
        })
        .collect();
    files.sort();
    if files.is_empty() {
        return Err(format!("no .c/.m sources under {}", src_dir.display()));
    }

    // (c_name, spelling, source) for every occurrence in the tree.
    let mut occurrences: Vec<(String, String, String)> = Vec::new();
    for path in &files {
        let file_name = path
            .file_name()
            .and_then(|name| name.to_str())
            .ok_or_else(|| format!("non-UTF-8 file name {}", path.display()))?;
        // Several GNU sources are Latin-1 (msdos.c among them); the DEFSYM
        // spellings themselves are ASCII, so a lossy decode cannot alter a
        // name and keeps the scan independent of the file's encoding.
        let bytes = fs::read(path).map_err(|error| format!("read {}: {error}", path.display()))?;
        let text = String::from_utf8_lossy(&bytes);
        let mut scanned = Vec::new();
        scan_source(&text, &mut scanned);
        for (c_name, spelling) in scanned {
            occurrences.push((c_name, spelling, file_name.to_string()));
        }
    }

    let mut by_c_name: BTreeMap<String, Vec<(String, String)>> = BTreeMap::new();
    let mut all_spellings: BTreeMap<String, (String, String)> = BTreeMap::new();
    for (c_name, spelling, source) in occurrences {
        all_spellings
            .entry(spelling.clone())
            .or_insert_with(|| (c_name.clone(), source.clone()));
        by_c_name
            .entry(c_name)
            .or_default()
            .push((spelling, source));
    }

    // For every C identifier, each profile that compiles a defining source
    // contributes the spelling make-docfile would keep: the one in the
    // earliest-scanned file of that profile's object list.
    let mut by_spelling: BTreeMap<String, (String, ProfileMask, String)> = BTreeMap::new();
    for (c_name, defining) in by_c_name {
        for (profile, order) in &scan_orders {
            let chosen = defining
                .iter()
                .filter_map(|(spelling, source)| {
                    order
                        .iter()
                        .position(|compiled| compiled == source)
                        .map(|rank| (rank, spelling, source))
                })
                .min_by_key(|(rank, _, _)| *rank);
            let Some((_, spelling, source)) = chosen else {
                continue;
            };
            let entry = by_spelling
                .entry(spelling.clone())
                .or_insert_with(|| (c_name.clone(), ProfileMask::NONE, source.clone()));
            entry.1 = entry.1.union(ProfileMask(profile.bit()));
            // Keep the lexicographically first identifier as the row's C name
            // so the make-docfile order is stable across profiles.
            if c_name < entry.0 {
                entry.0 = c_name.clone();
            }
        }
    }

    // Spellings no reference profile compiles stay in the ledger with a
    // `none` gate: they document the source surface the profile model
    // covers, and the generator still refuses to emit them.
    for (spelling, (c_name, source)) in all_spellings {
        by_spelling
            .entry(spelling)
            .or_insert_with(|| (c_name, ProfileMask::NONE, source));
    }

    let mut rows: Vec<Row> = by_spelling
        .into_iter()
        .map(|(name, (c_name, mask, source))| Row {
            gate: if UNINTERNED.contains(&name.as_str()) {
                Gate::Uninterned
            } else {
                Gate::Profiles(mask)
            },
            name,
            c_name,
            source,
        })
        .collect();
    rows.sort_by(|left, right| {
        sort_key(left)
            .cmp(&sort_key(right))
            .then_with(|| left.name.cmp(&right.name))
    });
    Ok(rows)
}

/// Resolve `--source`: accepts the GNU checkout root or its `src` directory.
pub fn source_src_dir(source: &Path) -> Result<PathBuf, String> {
    if source.join("src").join("lisp.h").is_file() {
        return Ok(source.join("src"));
    }
    if source.join("lisp.h").is_file() {
        return Ok(source.to_path_buf());
    }
    Err(format!(
        "{} does not look like a GNU Emacs checkout (or its src directory)",
        source.display()
    ))
}

pub fn render_ledger(rows: &[Row]) -> String {
    let mut out = String::from(LEDGER_HEADER);
    for row in rows {
        writeln!(
            out,
            "{}\t{}\t{}\t{}",
            row.name,
            row.gate.as_str(),
            row.c_name,
            row.source
        )
        .expect("write to String");
    }
    out
}

pub fn parse_ledger(text: &str) -> Result<Vec<Row>, String> {
    let mut rows = Vec::new();
    for (index, line) in text.lines().enumerate() {
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let fields: Vec<&str> = line.split('\t').collect();
        if fields.len() != 4 {
            return Err(format!(
                "ledger line {}: expected 4 tab-separated fields, got {}",
                index + 1,
                fields.len()
            ));
        }
        let gate = Gate::parse(fields[1])
            .ok_or_else(|| format!("ledger line {}: unknown gate `{}`", index + 1, fields[1]))?;
        rows.push(Row {
            name: fields[0].to_string(),
            gate,
            c_name: fields[2].to_string(),
            source: fields[3].to_string(),
        });
    }
    if rows.is_empty() {
        return Err("ledger is empty".to_string());
    }
    Ok(rows)
}

const GENERATED_HEADER: &str = r#"// Generated by the GNU DEFSYM boot-membership generator (`cargo xtask gnu-defsyms`).
// Source of truth: crates/neovm-value/src/intern/gnu_defsyms.snapshot.tsv,
// extracted from GNU 31.1 a360712c9d272d950d8d8255ef74570f7e90b7d9.
// Do not edit by hand; run the generator and commit its output.
//
// GNU's `init_obarray_once` (src/lread.c:5193-5203) interns every compiled
// `defsym_name[]` spelling into the initial obarray with no function cell and
// no value; `make-docfile.c:638-667` fixes the order (Qnil, Qt, Qunbound,
// Qerror, Qlambda first, then strcmp of the C identifier). See
// crates/neovm-value/build_support/gnu_defsyms.rs for the profile model.

/// The build profiles a GNU DEFSYM spelling belongs to.
///
/// A profile is the configure object list of a reference build: `linux` is
/// the attested GTK3/X11 configuration, `macos` the NS build, `windows` the
/// MinGW-w64 build. A spelling is interned when any profile compiling a
/// source that DEFSYMs it is the profile this binary is built for.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) struct DefsymGate(pub(crate) u8);

impl DefsymGate {
    pub(crate) const LINUX: u8 = 1;
    pub(crate) const MACOS: u8 = 2;
    pub(crate) const WINDOWS: u8 = 4;

    /// Whether the spelling belongs to this build's obarray.
    pub(crate) const fn is_active(self) -> bool {
        self.0 & CURRENT_PROFILE != 0
    }
}

/// The profile this binary was built for. Non-macOS, non-Windows builds use
/// the Linux (X11/GTK) object list.
const CURRENT_PROFILE: u8 = if cfg!(windows) {
    DefsymGate::WINDOWS
} else if cfg!(target_os = "macos") {
    DefsymGate::MACOS
} else {
    DefsymGate::LINUX
};

"#;

fn gate_expression(mask: ProfileMask) -> String {
    let mut parts = Vec::new();
    if mask.0 & Profile::Linux.bit() != 0 {
        parts.push("DefsymGate::LINUX");
    }
    if mask.0 & Profile::Macos.bit() != 0 {
        parts.push("DefsymGate::MACOS");
    }
    if mask.0 & Profile::Windows.bit() != 0 {
        parts.push("DefsymGate::WINDOWS");
    }
    if parts.is_empty() {
        "0".to_string()
    } else {
        parts.join(" | ")
    }
}

pub fn render_generated(
    rows: &[Row],
    c_interns: &[CInternRow],
    c_defuns: &[CInternRow],
) -> Result<String, String> {
    let emitted: Vec<&Row> = rows.iter().filter(|row| row.gate.is_emitted()).collect();
    if emitted.is_empty() {
        return Err("no emitted rows in the ledger".to_string());
    }
    for pair in emitted.windows(2) {
        let left = (sort_key(pair[0]), pair[0].name.as_str());
        let right = (sort_key(pair[1]), pair[1].name.as_str());
        if left > right {
            return Err(format!(
                "ledger is not in make-docfile order: `{}` after `{}`",
                pair[1].c_name, pair[0].c_name
            ));
        }
    }
    // Every profile must have rows, and the attested Linux set must stay the
    // set the oracle run validated: a model mistake that drops or adds a
    // common file is visible here as a count change.
    for profile in Profile::ALL {
        if !emitted
            .iter()
            .any(|row| row.gate.mask().0 & profile.bit() != 0)
        {
            return Err(format!("no rows for the `{}` profile", profile.name()));
        }
    }

    let mut out = String::from(GENERATED_HEADER);
    writeln!(
        out,
        "/// Every GNU DEFSYM spelling this platform interns at boot, in\n\
         /// make-docfile order. {} rows.\n\
         #[rustfmt::skip]\n\
         pub(crate) static GNU_DEFSYMS: &[(&str, DefsymGate)] = &[",
        emitted.len()
    )
    .expect("write to String");
    for row in &emitted {
        let mask = row.gate.mask();
        writeln!(
            out,
            "    ({}, DefsymGate({})),",
            rust_string_literal(&row.name),
            gate_expression(mask)
        )
        .expect("write to String");
    }
    out.push_str("];\n");

    // The same rows sorted by spelling, for the boot-surface normalizer's
    // membership test (`is_active_gnu_defsym_spelling`).
    let mut by_spelling = emitted.clone();
    by_spelling.sort_by(|left, right| left.name.cmp(&right.name));
    writeln!(
        out,
        "\n/// Every row above, sorted by Lisp spelling for binary-search membership\n\
         /// tests. {} rows.\n\
         #[rustfmt::skip]\n\
         pub(crate) static GNU_DEFSYMS_BY_SPELLING: &[(&str, DefsymGate)] = &[",
        by_spelling.len()
    )
    .expect("write to String");
    for row in &by_spelling {
        writeln!(
            out,
            "    ({}, DefsymGate({})),",
            rust_string_literal(&row.name),
            gate_expression(row.gate.mask())
        )
        .expect("write to String");
    }
    out.push_str("];\n");

    // The startup-uninterned spellings, sorted, for the shared helper the
    // startup census consumes instead of maintaining a second list.
    let mut uninterned: Vec<&Row> = rows
        .iter()
        .filter(|row| row.gate == Gate::Uninterned)
        .collect();
    uninterned.sort_by(|left, right| left.name.cmp(&right.name));
    writeln!(
        out,
        "\n/// GNU compiles these DEFSYM spellings and then removes them from the\n\
         /// initial obarray (`Funintern`), or never interns them at all.\n\
         /// {} spellings, sorted.\n\
         #[rustfmt::skip]\n\
         pub(crate) static GNU_UNINTERNED_SPELLINGS: &[&str] = &[",
        uninterned.len()
    )
    .expect("write to String");
    for row in &uninterned {
        writeln!(out, "    {},", rust_string_literal(&row.name)).expect("write to String");
    }
    out.push_str("];\n");

    // Literal C intern spellings. These are the names GNU's `syms_of_*` code
    // passes to `intern_c_string` directly, so no `DEFSYM` row covers them.
    let emitted_c: Vec<&CInternRow> = c_interns
        .iter()
        .filter(|row| !row.gate.is_empty())
        .collect();
    writeln!(
        out,
        "\n/// Every literal `intern_c_string`/`intern` spelling the compiled GNU\n\
         /// sources intern at startup, in source-file then spelling order.\n\
         /// {} rows.\n\
         #[rustfmt::skip]\n\
         pub(crate) static GNU_C_INTERNS: &[(&str, DefsymGate)] = &[",
        emitted_c.len()
    )
    .expect("write to String");
    for row in &emitted_c {
        writeln!(
            out,
            "    ({}, DefsymGate({})),",
            rust_string_literal(&row.name),
            gate_expression(row.gate)
        )
        .expect("write to String");
    }
    out.push_str("];\n");
    let mut by_spelling: Vec<&CInternRow> = emitted_c.clone();
    by_spelling.sort_by(|left, right| left.name.cmp(&right.name));
    writeln!(
        out,
        "\n/// `GNU_C_INTERNS` sorted by spelling for the normalizer's membership\n\
         /// test. {} rows.\n\
         #[rustfmt::skip]\n\
         pub(crate) static GNU_C_INTERNS_BY_SPELLING: &[(&str, DefsymGate)] = &[",
        by_spelling.len()
    )
    .expect("write to String");
    for row in &by_spelling {
        writeln!(
            out,
            "    ({}, DefsymGate({})),",
            rust_string_literal(&row.name),
            gate_expression(row.gate)
        )
        .expect("write to String");
    }
    out.push_str("];\n");

    let emitted_d: Vec<&CInternRow> = c_defuns.iter().filter(|row| !row.gate.is_empty()).collect();
    writeln!(
        out,
        "\n/// Every literal DEFUN subr name of the compiled GNU objects, in\n\
         /// source-file then spelling order. `defsubr` interns each one, so\n\
         /// GNU's image carries names of subrs this port declines.\n\
         /// {} rows.\n\
         #[rustfmt::skip]\n\
         pub(crate) static GNU_C_DEFUNS: &[(&str, DefsymGate)] = &[",
        emitted_d.len()
    )
    .expect("write to String");
    for row in &emitted_d {
        writeln!(
            out,
            "    ({}, DefsymGate({})),",
            rust_string_literal(&row.name),
            gate_expression(row.gate)
        )
        .expect("write to String");
    }
    out.push_str("];\n");
    let mut by_spelling_d: Vec<&CInternRow> = emitted_d.clone();
    by_spelling_d.sort_by(|left, right| left.name.cmp(&right.name));
    writeln!(
        out,
        "\n/// `GNU_C_DEFUNS` sorted by spelling for the normalizer's membership\n\
         /// test. {} rows.\n\
         #[rustfmt::skip]\n\
         pub(crate) static GNU_C_DEFUNS_BY_SPELLING: &[(&str, DefsymGate)] = &[",
        by_spelling_d.len()
    )
    .expect("write to String");
    for row in &by_spelling_d {
        writeln!(
            out,
            "    ({}, DefsymGate({})),",
            rust_string_literal(&row.name),
            gate_expression(row.gate)
        )
        .expect("write to String");
    }
    out.push_str("];\n");

    writeln!(
        out,
        "\nconst _: () = assert!(GNU_DEFSYMS.len() == {});\n\
         const _: () = assert!(GNU_DEFSYMS_BY_SPELLING.len() == GNU_DEFSYMS.len());\n\
         const _: () = assert!(GNU_UNINTERNED_SPELLINGS.len() == {});\n\
         const _: () = assert!(GNU_C_INTERNS.len() == {});\n\
         const _: () = assert!(GNU_C_INTERNS_BY_SPELLING.len() == GNU_C_INTERNS.len());\n\
         const _: () = assert!(GNU_C_DEFUNS.len() == {});\n\
         const _: () = assert!(GNU_C_DEFUNS_BY_SPELLING.len() == GNU_C_DEFUNS.len());",
        emitted.len(),
        uninterned.len(),
        emitted_c.len(),
        emitted_d.len()
    )
    .expect("write to String");
    Ok(out)
}

fn rust_string_literal(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for character in text.chars() {
        match character {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            other => out.push(other),
        }
    }
    out.push('"');
    out
}

/// Render the generated table from the checked-in ledger.
pub fn rendered(repo_root: &Path) -> Result<String, String> {
    let ledger_path = repo_root.join(LEDGER);
    let text = fs::read_to_string(&ledger_path)
        .map_err(|error| format!("read {}: {error}", ledger_path.display()))?;
    let rows = parse_ledger(&text)?;
    let c_intern_path = repo_root.join(C_INTERN_LEDGER);
    let c_text = fs::read_to_string(&c_intern_path)
        .map_err(|error| format!("read {}: {error}", c_intern_path.display()))?;
    let c_interns = parse_c_intern_ledger(&c_text)?;
    let c_defun_path = repo_root.join(C_DEFUN_LEDGER);
    let d_text = fs::read_to_string(&c_defun_path)
        .map_err(|error| format!("read {}: {error}", c_defun_path.display()))?;
    let c_defuns = parse_c_defun_ledger(&d_text)?;
    render_generated(&rows, &c_interns, &c_defuns)
}

/// Write (or `--check`) the ledger and generated table.
pub fn generate(repo_root: &Path, check: bool, source: Option<&Path>) -> Result<(), String> {
    let ledger_path = repo_root.join(LEDGER);
    let generated_path = repo_root.join(GENERATED);

    if source.is_none() && !check {
        return Err(
            "writing needs the pinned GNU source: pass --source <checkout> or set GNU_EMACS_SOURCE"
                .to_string(),
        );
    }

    let c_intern_path = repo_root.join(C_INTERN_LEDGER);
    let c_defun_path = repo_root.join(C_DEFUN_LEDGER);

    let extracted = match source {
        Some(source) => {
            let src_dir = source_src_dir(source)?;
            let rows = extract(&src_dir)?;
            let c_interns = extract_c_interns(&src_dir)?;
            let c_defuns = extract_c_defuns(&src_dir)?;
            Some((src_dir, rows, c_interns, c_defuns))
        }
        None => None,
    };

    if let Some((src_dir, rows, c_interns, c_defuns)) = &extracted {
        let extracted_ledger = render_ledger(rows);
        let extracted_c_ledger = render_c_intern_ledger(c_interns);
        let extracted_d_ledger = render_c_defun_ledger(c_defuns);
        if check {
            let tracked = fs::read_to_string(&ledger_path)
                .map_err(|error| format!("read {}: {error}", ledger_path.display()))?;
            if tracked != extracted_ledger {
                return Err(format!(
                    "{LEDGER} is stale against {}; run `cargo xtask gnu-defsyms --source <checkout>`",
                    src_dir.display()
                ));
            }
            let tracked_c = fs::read_to_string(&c_intern_path)
                .map_err(|error| format!("read {}: {error}", c_intern_path.display()))?;
            if tracked_c != extracted_c_ledger {
                return Err(format!(
                    "{C_INTERN_LEDGER} is stale against {}; run `cargo xtask gnu-defsyms --source <checkout>`",
                    src_dir.display()
                ));
            }
            let tracked_d = fs::read_to_string(&c_defun_path)
                .map_err(|error| format!("read {}: {error}", c_defun_path.display()))?;
            if tracked_d != extracted_d_ledger {
                return Err(format!(
                    "{C_DEFUN_LEDGER} is stale against {}; run `cargo xtask gnu-defsyms --source <checkout>`",
                    src_dir.display()
                ));
            }
        } else {
            fs::write(&ledger_path, &extracted_ledger)
                .map_err(|error| format!("write {}: {error}", ledger_path.display()))?;
            fs::write(&c_intern_path, &extracted_c_ledger)
                .map_err(|error| format!("write {}: {error}", c_intern_path.display()))?;
            fs::write(&c_defun_path, &extracted_d_ledger)
                .map_err(|error| format!("write {}: {error}", c_defun_path.display()))?;
        }
    }

    let rows = match &extracted {
        Some((_, rows, _, _)) => rows.clone(),
        None => {
            let text = fs::read_to_string(&ledger_path)
                .map_err(|error| format!("read {}: {error}", ledger_path.display()))?;
            parse_ledger(&text)?
        }
    };
    let c_interns = match &extracted {
        Some((_, _, c_interns, _)) => c_interns.clone(),
        None => {
            let text = fs::read_to_string(&c_intern_path)
                .map_err(|error| format!("read {}: {error}", c_intern_path.display()))?;
            parse_c_intern_ledger(&text)?
        }
    };

    let c_defuns = match &extracted {
        Some((_, _, _, c_defuns)) => c_defuns.clone(),
        None => {
            let text = fs::read_to_string(&c_defun_path)
                .map_err(|error| format!("read {}: {error}", c_defun_path.display()))?;
            parse_c_defun_ledger(&text)?
        }
    };

    let generated = render_generated(&rows, &c_interns, &c_defuns)?;
    if check {
        let tracked = fs::read_to_string(&generated_path)
            .map_err(|error| format!("read {}: {error}", generated_path.display()))?;
        if tracked != generated {
            return Err(format!(
                "{GENERATED} is stale; run `cargo xtask gnu-defsyms`"
            ));
        }
    } else {
        fs::write(&generated_path, &generated)
            .map_err(|error| format!("write {}: {error}", generated_path.display()))?;
    }
    Ok(())
}

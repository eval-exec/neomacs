use serde::Deserialize;
use std::fmt;
use std::path::Path;
use std::process::Command;

const WINDOWS_TARGET: &str = "x86_64-pc-windows-msvc";

#[derive(Clone, Debug, Deserialize, PartialEq, Eq)]
#[serde(transparent)]
struct PackageId(String);

#[derive(Debug, Deserialize)]
struct CargoPackage {
    id: PackageId,
    name: String,
}

#[derive(Debug, Deserialize)]
struct CargoNodeDependency {
    name: String,
    pkg: PackageId,
}

#[derive(Debug, Deserialize)]
struct CargoNode {
    id: PackageId,
    deps: Vec<CargoNodeDependency>,
}

#[derive(Debug, Deserialize)]
struct CargoResolve {
    nodes: Vec<CargoNode>,
}

#[derive(Debug, Deserialize)]
struct CargoMetadata {
    packages: Vec<CargoPackage>,
    resolve: CargoResolve,
}

/// A nominal native type family that must not split across collaborating crates.
///
/// Rust correctly treats COM interfaces generated by different `windows` crate
/// versions as unrelated types. `wgpu-hal` passes those interfaces through
/// `gpu-allocator`, so both crates must resolve the same package ID even though
/// unrelated consumers may legitimately retain another `windows` version.
#[derive(Debug, PartialEq, Eq)]
enum CoherenceViolation {
    PackageCardinality {
        package: &'static str,
        found: usize,
    },
    MissingDependency {
        package: &'static str,
        dependency: &'static str,
    },
    SplitWindowsComFamily {
        wgpu_hal: PackageId,
        gpu_allocator: PackageId,
    },
}

impl fmt::Display for CoherenceViolation {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::PackageCardinality { package, found } => write!(
                formatter,
                "expected exactly one `{package}` package in the Windows dependency graph, found {found}"
            ),
            Self::MissingDependency {
                package,
                dependency,
            } => write!(
                formatter,
                "`{package}` is missing its Windows `{dependency}` dependency"
            ),
            Self::SplitWindowsComFamily {
                wgpu_hal,
                gpu_allocator,
            } => write!(
                formatter,
                "Windows native dependency coherence violation: `wgpu-hal` uses `{}`, but its `gpu-allocator` collaborator uses `{}`; Direct3D COM values from different `windows` crate versions are distinct Rust types",
                wgpu_hal.0, gpu_allocator.0
            ),
        }
    }
}

pub(super) fn run(repo_root: &Path) -> super::Result<()> {
    let output = Command::new("cargo")
        .current_dir(repo_root)
        .args([
            "metadata",
            "--format-version",
            "1",
            "--locked",
            "--filter-platform",
            WINDOWS_TARGET,
        ])
        .output()?;
    if !output.status.success() {
        return Err(format!(
            "cargo metadata for {WINDOWS_TARGET} failed:\n{}",
            String::from_utf8_lossy(&output.stderr)
        )
        .into());
    }

    let metadata: CargoMetadata = serde_json::from_slice(&output.stdout)?;
    validate_windows_com_family(&metadata)
        .map_err(|violation| -> super::DynError { violation.to_string().into() })?;
    println!("Windows native dependency type families are coherent");
    Ok(())
}

fn validate_windows_com_family(metadata: &CargoMetadata) -> Result<(), CoherenceViolation> {
    let wgpu_hal = unique_node(metadata, "wgpu-hal")?;
    let gpu_allocator_id = dependency_id(wgpu_hal, "wgpu-hal", "gpu_allocator")?;
    let gpu_allocator = metadata
        .resolve
        .nodes
        .iter()
        .find(|node| node.id == *gpu_allocator_id)
        .ok_or(CoherenceViolation::PackageCardinality {
            package: "gpu-allocator",
            found: 0,
        })?;

    let wgpu_windows = dependency_id(wgpu_hal, "wgpu-hal", "windows")?;
    let allocator_windows = dependency_id(gpu_allocator, "gpu-allocator", "windows")?;
    if wgpu_windows != allocator_windows {
        return Err(CoherenceViolation::SplitWindowsComFamily {
            wgpu_hal: wgpu_windows.clone(),
            gpu_allocator: allocator_windows.clone(),
        });
    }
    Ok(())
}

fn unique_node<'a>(
    metadata: &'a CargoMetadata,
    package_name: &'static str,
) -> Result<&'a CargoNode, CoherenceViolation> {
    let package_ids: Vec<_> = metadata
        .packages
        .iter()
        .filter(|package| package.name == package_name)
        .map(|package| &package.id)
        .collect();
    if package_ids.len() != 1 {
        return Err(CoherenceViolation::PackageCardinality {
            package: package_name,
            found: package_ids.len(),
        });
    }
    metadata
        .resolve
        .nodes
        .iter()
        .find(|node| node.id == *package_ids[0])
        .ok_or(CoherenceViolation::PackageCardinality {
            package: package_name,
            found: 0,
        })
}

fn dependency_id<'a>(
    node: &'a CargoNode,
    package: &'static str,
    dependency: &'static str,
) -> Result<&'a PackageId, CoherenceViolation> {
    node.deps
        .iter()
        .find(|candidate| candidate.name == dependency)
        .map(|candidate| &candidate.pkg)
        .ok_or(CoherenceViolation::MissingDependency {
            package,
            dependency,
        })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rejects_collaborators_from_different_windows_com_type_families() {
        let metadata = metadata_with_windows_versions("0.62.2", "0.54.0");

        assert!(matches!(
            validate_windows_com_family(&metadata),
            Err(CoherenceViolation::SplitWindowsComFamily {
                wgpu_hal: PackageId(wgpu),
                gpu_allocator: PackageId(allocator),
            }) if wgpu.ends_with("windows@0.62.2") && allocator.ends_with("windows@0.54.0")
        ));
    }

    #[test]
    fn accepts_collaborators_from_one_windows_com_type_family() {
        let metadata = metadata_with_windows_versions("0.62.2", "0.62.2");

        assert_eq!(validate_windows_com_family(&metadata), Ok(()));
    }

    fn metadata_with_windows_versions(
        wgpu_windows_version: &str,
        allocator_windows_version: &str,
    ) -> CargoMetadata {
        let wgpu_hal = package_id("wgpu-hal", "30.0.1");
        let gpu_allocator = package_id("gpu-allocator", "0.28.0");
        let wgpu_windows = package_id("windows", wgpu_windows_version);
        let allocator_windows = package_id("windows", allocator_windows_version);
        let mut packages = vec![
            CargoPackage {
                id: wgpu_hal.clone(),
                name: "wgpu-hal".into(),
            },
            CargoPackage {
                id: gpu_allocator.clone(),
                name: "gpu-allocator".into(),
            },
        ];
        for id in [&wgpu_windows, &allocator_windows] {
            if !packages.iter().any(|package| package.id == *id) {
                packages.push(CargoPackage {
                    id: id.clone(),
                    name: "windows".into(),
                });
            }
        }
        CargoMetadata {
            packages,
            resolve: CargoResolve {
                nodes: vec![
                    CargoNode {
                        id: wgpu_hal,
                        deps: vec![
                            CargoNodeDependency {
                                name: "gpu_allocator".into(),
                                pkg: gpu_allocator.clone(),
                            },
                            CargoNodeDependency {
                                name: "windows".into(),
                                pkg: wgpu_windows,
                            },
                        ],
                    },
                    CargoNode {
                        id: gpu_allocator,
                        deps: vec![CargoNodeDependency {
                            name: "windows".into(),
                            pkg: allocator_windows,
                        }],
                    },
                ],
            },
        }
    }

    fn package_id(name: &str, version: &str) -> PackageId {
        PackageId(format!(
            "registry+https://github.com/rust-lang/crates.io-index#{name}@{version}"
        ))
    }
}

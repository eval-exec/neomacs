pub(super) fn lookup(name: &str) -> Option<u32> {
    CACHED_NAME_ALIASES
        .binary_search_by(|&(candidate, _)| {
            candidate
                .bytes()
                .cmp(name.bytes().map(|byte| byte.to_ascii_uppercase()))
        })
        .ok()
        .map(|index| u32::from(CACHED_NAME_ALIASES[index].1))
}

//! Generator for the H3 unit-runtime upper-subr stand-in source.
//!
//! `crates/neovm-eval/src/upper_subrs.generated.rs` is the checked-in Rust
//! source that eval's and display's cfg(test) unit runtimes include. Its header
//! forbids hand edits. This module restores the lost H3 generator: it renders
//! the file byte-for-byte from the H3 ledger
//! (`upper_subrs.snapshot.tsv`: name, min, max, layer, cfg) and validates that
//! ledger against the canonical plan artifacts, which are themselves derived
//! from the production manifest by [`canonical_subr_plan`].
//!
//! One home per fact:
//! * membership, arity and cfg classes: the production manifest, via the
//!   canonical plan (`canonical_subr_names.tsv`, itself checked against the
//!   manifest by `cargo xtask canonical-subr-plan --check`);
//! * H3 registration order and the per-name layer label: the ledger, whose row
//!   order is the H3 order (direct declarations in manifest source order,
//!   followed by the non-eval localized batches in batch-call order);
//! * this module: rendering and drift checks only.
//!
//! Regenerate with `cargo xtask upper-subrs` (writes) or
//! `cargo xtask upper-subrs --check` (fails on drift).

use std::path::Path;

// The cfg-label vocabulary is shared with eval and the plan generator;
// include the one host_cfg source so xtask cannot drift. Only the vocabulary
// is included: the activity predicate stays in eval's host_cfg_active module,
// because xtask compiles without the workspace build-script probe.
#[path = "../src/host_cfg.rs"]
mod host_cfg;

pub const LEDGER: &str = "crates/neovm-eval/src/upper_subrs.snapshot.tsv";
pub const GENERATED: &str = "crates/neovm-eval/src/upper_subrs.generated.rs";
pub const CANONICAL_NAMES: &str = "crates/neovm-eval/src/canonical_subr_names.tsv";
pub const CANONICAL_PLAN: &str = "crates/neovm-eval/src/canonical_subr_step_plan.tsv";

const HEADER: &str = "// Generated by the eval unit-runtime snapshot generator (H3).\n\
// One panicking AbsentLayer subr per upper-layer C14 name, in production\n\
// registration order. Regenerate from the post-split manifest and the\n\
// non-eval localized batches; the core-side names+order test is the P2 gate.\n\
// Do not edit by hand.\n\
\n\
// (included inside the cfg(test) unit_runtime module)\n";

const TABLE_HEAD: &str = "static UPPER_SUBRS: &[(&str, u16, Option<u16>, fn(&mut Context, Vec<Value>) -> EvalResult)] = &[\n";

/// One ledger row in H3 registration order.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Row {
    pub name: String,
    pub min: u16,
    pub max: Option<u16>,
    pub layer: String,
    pub cfg: String,
}

fn read(repo_root: &Path, relative: &str) -> Result<String, String> {
    std::fs::read_to_string(repo_root.join(relative))
        .map_err(|error| format!("read {relative}: {error}"))
}

fn parse_ledger(text: &str) -> Result<Vec<Row>, String> {
    let mut rows = Vec::new();
    for (index, line) in text.lines().enumerate() {
        if index == 0 {
            if line != "name\tmin\tmax\tlayer\tcfg" {
                return Err(format!("{LEDGER}: unexpected header {line:?}"));
            }
            continue;
        }
        if line.trim().is_empty() {
            continue;
        }
        let fields: Vec<&str> = line.split('\t').collect();
        if fields.len() != 5 {
            return Err(format!("{LEDGER} line {}: expected 5 columns", index + 1));
        }
        let min: u16 = fields[1]
            .parse()
            .map_err(|_| format!("{LEDGER} line {}: bad min {:?}", index + 1, fields[1]))?;
        let max = if fields[2] == "-" {
            None
        } else {
            Some(
                fields[2]
                    .parse()
                    .map_err(|_| format!("{LEDGER} line {}: bad max {:?}", index + 1, fields[2]))?,
            )
        };
        if max.is_some_and(|max| max < min) {
            return Err(format!("{LEDGER} line {}: max below min", index + 1));
        }
        if host_cfg::HostCfgClass::from_label(fields[4]).is_none() {
            return Err(format!(
                "{LEDGER} line {}: unknown cfg class {:?}",
                index + 1,
                fields[4]
            ));
        }
        rows.push(Row {
            name: fields[0].to_owned(),
            min,
            max,
            layer: fields[3].to_owned(),
            cfg: fields[4].to_owned(),
        });
    }
    if rows.is_empty() {
        return Err(format!("{LEDGER}: no rows"));
    }
    Ok(rows)
}

/// The canonical plan's (name, min, max) rows, used to prove the ledger still
/// matches the production manifest's membership and arities.
fn parse_canonical_names(text: &str) -> Result<Vec<(String, u16, Option<u16>)>, String> {
    let mut rows = Vec::new();
    for (index, line) in text.lines().enumerate() {
        if index == 0 {
            if line != "name\tmin\tmax\tlayer\tcfg" {
                return Err(format!("{CANONICAL_NAMES}: unexpected header {line:?}"));
            }
            continue;
        }
        if line.trim().is_empty() {
            continue;
        }
        let fields: Vec<&str> = line.split('\t').collect();
        if fields.len() != 5 {
            return Err(format!(
                "{CANONICAL_NAMES} line {}: expected 5 columns",
                index + 1
            ));
        }
        let min: u16 = fields[1]
            .parse()
            .map_err(|_| format!("{CANONICAL_NAMES} line {}: bad min", index + 1))?;
        let max = if fields[2] == "-" {
            None
        } else {
            Some(
                fields[2]
                    .parse()
                    .map_err(|_| format!("{CANONICAL_NAMES} line {}: bad max", index + 1))?,
            )
        };
        rows.push((fields[0].to_owned(), min, max));
    }
    Ok(rows)
}

/// The canonical plan rows that are NOT replayed by an eval-owned registrar:
/// the upper stand-in source covers exactly the `upper_segment` and
/// `display_segment` steps. The plan is ordered by production registration;
/// the H3 ledger keeps its own direct-then-batch order, so only the set and
/// per-name arities are compared here.
fn plan_upper_rows(
    canonical: &[(String, u16, Option<u16>)],
    plan: &str,
) -> Result<Vec<(String, u16, Option<u16>)>, String> {
    let mut upper = Vec::new();
    for (index, line) in plan.lines().enumerate() {
        if index == 0 {
            if line != "step\tkind\tid\tlayer\tfirst\tcount\tmarker" {
                return Err(format!("{CANONICAL_PLAN}: unexpected header {line:?}"));
            }
            continue;
        }
        if line.trim().is_empty() {
            continue;
        }
        let fields: Vec<&str> = line.split('\t').collect();
        if fields.len() != 7 {
            return Err(format!(
                "{CANONICAL_PLAN} line {}: expected 7 columns",
                index + 1
            ));
        }
        if fields[1] == "eval_call" {
            continue;
        }
        let first: usize = fields[4]
            .parse()
            .map_err(|_| format!("{CANONICAL_PLAN} line {}: bad first", index + 1))?;
        let count: usize = fields[5]
            .parse()
            .map_err(|_| format!("{CANONICAL_PLAN} line {}: bad count", index + 1))?;
        let end = first - 1 + count;
        if end > canonical.len() {
            return Err(format!(
                "{CANONICAL_PLAN} line {}: row range {}..{} exceeds {} names",
                index + 1,
                first,
                end,
                canonical.len()
            ));
        }
        upper.extend(canonical[first - 1..end].iter().cloned());
    }
    if upper.is_empty() {
        return Err(format!("{CANONICAL_PLAN}: no upper rows"));
    }
    Ok(upper)
}

/// Validate the ledger against the plan's upper rows: identical name set and
/// identical arity per name. Order is the ledger's H3 order and is not
/// imposed by the plan (the plan records production order; the H3 ledger
/// records the direct-then-batch order the unit-runtime source has always
/// used).
fn validate_against_plan(
    rows: &[Row],
    canonical: &[(String, u16, Option<u16>)],
) -> Result<(), String> {
    use std::collections::BTreeMap;
    let mut plan: BTreeMap<&str, (u16, Option<u16>)> = BTreeMap::new();
    for (name, min, max) in canonical {
        if plan.insert(name.as_str(), (*min, *max)).is_some() {
            return Err(format!("duplicate canonical name {name:?}"));
        }
    }
    let mut seen: BTreeMap<&str, (u16, Option<u16>)> = BTreeMap::new();
    for row in rows {
        if seen.insert(row.name.as_str(), (row.min, row.max)).is_some() {
            return Err(format!("duplicate upper ledger name {:?}", row.name));
        }
        match plan.get(row.name.as_str()) {
            Some((min, max)) if (*min, *max) == (row.min, row.max) => {}
            Some((min, max)) => {
                return Err(format!(
                    "{}: ledger arity {}({:?}) != canonical plan arity {}({:?})",
                    row.name, row.min, row.max, min, max
                ));
            }
            None => {
                return Err(format!(
                    "upper ledger name {:?} is not in the canonical plan",
                    row.name
                ));
            }
        }
    }
    if seen.len() != plan.len() {
        let missing: Vec<&str> = plan
            .keys()
            .filter(|name| !seen.contains_key(**name))
            .copied()
            .take(8)
            .collect();
        return Err(format!(
            "upper ledger covers {}/{} canonical names; missing e.g. {missing:?}",
            seen.len(),
            plan.len()
        ));
    }
    Ok(())
}

fn cfg_attribute(cfg: &str) -> Result<Option<&'static str>, String> {
    Ok(Some(match cfg {
        "always" => return Ok(None),
        "macos" => "target_os = \"macos\"",
        "windows" => "windows",
        "not-macos" => "not(target_os = \"macos\")",
        "x11-only" => "not(any(windows, target_os = \"macos\"))",
        "dbus" => "neomacs_have_dbus",
        "sqlite" => "feature = \"sqlite\"",
        other => {
            return Err(format!(
                "cfg class {other:?} has no rendered attribute; add it here and to HostCfgClass"
            ));
        }
    }))
}

/// Render the checked-in Rust source, byte-for-byte.
pub fn render(rows: &[Row]) -> Result<String, String> {
    let mut out = String::with_capacity(rows.len() * 200 + HEADER.len() + TABLE_HEAD.len());
    out.push_str(HEADER);
    for (index, row) in rows.iter().enumerate() {
        if let Some(attribute) = cfg_attribute(&row.cfg)? {
            out.push_str(&format!("#[cfg({attribute})]\n"));
        }
        out.push_str(&format!(
            "fn upper_subr_{index:04}(_ctx: &mut Context, _args: Vec<Value>) -> EvalResult {{\n    s::absent_layer_panic(\"ABSENT-LAYER {}::{}\");\n}}\n\n",
            row.layer, row.name
        ));
    }
    out.push_str(TABLE_HEAD);
    for (index, row) in rows.iter().enumerate() {
        if let Some(attribute) = cfg_attribute(&row.cfg)? {
            out.push_str(&format!("    #[cfg({attribute})]\n"));
        }
        let max = row
            .max
            .map_or_else(|| "None".to_owned(), |max| format!("Some({max})"));
        out.push_str(&format!(
            "    (\"{}\", {}, {}, upper_subr_{index:04}),\n",
            row.name, row.min, max
        ));
    }
    out.push_str("];\n");
    Ok(out)
}

/// Build the rendered source from the live tree without touching it.
pub fn rendered(repo_root: &Path) -> Result<String, String> {
    if !host_cfg::HostCfgClass::vocabulary_round_trips() {
        return Err(
            "host cfg vocabulary does not round-trip; fix HostCfgClass::label/from_label \
             in crates/neovm-eval/src/host_cfg.rs"
                .to_owned(),
        );
    }
    let rows = parse_ledger(&read(repo_root, LEDGER)?)?;
    let canonical = parse_canonical_names(&read(repo_root, CANONICAL_NAMES)?)?;
    let plan_upper = plan_upper_rows(&canonical, &read(repo_root, CANONICAL_PLAN)?)?;
    validate_against_plan(&rows, &plan_upper)?;
    render(&rows)
}

/// Write (or, with `check`, verify) the generated source.
pub fn generate(repo_root: &Path, check: bool) -> Result<(), String> {
    let rendered = rendered(repo_root)?;
    let path = repo_root.join(GENERATED);
    if check {
        let checked_in =
            std::fs::read_to_string(&path).map_err(|error| format!("read {GENERATED}: {error}"))?;
        if checked_in != rendered {
            return Err(format!(
                "{GENERATED} is stale; run `cargo xtask upper-subrs`"
            ));
        }
    } else {
        std::fs::write(&path, rendered).map_err(|error| format!("write {GENERATED}: {error}"))?;
    }
    Ok(())
}
